# -*- coding: utf-8 -*-
"""Дописує рецепти для пунктів виду «штатна поведінка» — шаблоном, а не копіюванням.

Навіщо окремий генератор і чому це НЕ суперечить правилу «не генерувати рецепти».
`report_recipe_gaps.py` навмисно не генерує рецепти, і причина там названа: склад полів
у поданні, домени й значення залежать від клієнта, тому автогенерація дала б
правдоподібні й неправильні рецепти. Для **конфігурації** це так і лишається.

Але «штатна поведінка» — інший вид роботи, і вигадувати в ньому нічого. Пункт цього
виду означає: записувати нічого, застосунок робить це сам; наша робота — переконатися,
що застосунок став, і показати процес на живих документах. Обидва кроки однакові для
всіх 51 пункту, і різниця між ними тільки в моделі та в тому, що саме показуємо. Копіювати
такий рецепт 51 раз означало б розмножити текст, який ніхто не перечитає.

Тому: один шаблон `штатна_поведінка` і цей генератор, який дописує виклики для тих
пунктів, у яких рецепта ще немає. Кожен згенерований рецепт позначений полем
`джерело` — щоб було видно, що він **не** писався руками, і щоб будь-який із них можна
було замінити рукописним, коли зʼявиться потреба (генератор наявні не чіпає).

Чого генератор НЕ робить: не вигадує конфігурацію, не торкається пунктів інших видів,
не перезаписує вже описані пункти.

Запуск: python3 tools/gen_standard_recipes.py [--dry]
"""

import collections
import importlib.util
import io
import json
import sys

OD = collections.OrderedDict
RECIPES = 'data/recipes.json'
CMAP = 'data/config-map.json'
VERIFY = 'data/verify.json'
PRICE = 'data/price.json'

TEMPLATE = OD([
    ('нащо',
     'Пункт виду «штатна поведінка»: записувати в базу нічого, це робить сам застосунок. '
     'Робота складається з двох частин, і обидві справжні — переконатися, що застосунок '
     'став (на свіжій базі документів ще немає, тому перевіряємо наявність МОДЕЛІ, а не '
     'документа), і показати процес клієнтові на живих документах. Другий крок — послуга: '
     'у базі після нього артефакту не лишається, але робота зроблена, і пункт не має '
     'загубитися мовчки.'),
    ('аргументи', ['моделі', 'що_показати']),
    ('кроки', [
        OD([('дія', 'для_кожного'), ('перелік', '$арг.моделі'),
            ('крок', OD([('дія', 'перевірити'), ('модель', 'ir.model'),
                         ('домен', [['model', '=', '$елемент']]),
                         ('щонайменше', 1)]))]),
        OD([('дія', 'послуга'), ('опис', '$арг.що_показати'),
            ('нащо', 'показ на живих документах — частина здачі позиції: клієнт мусить '
                     'побачити процес у своїй базі, а не на слайдах')]),
    ]),
])


def main(argv):
    spec = importlib.util.spec_from_file_location('rg', 'tools/report_recipe_gaps.py')
    rg = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(rg)

    R = json.load(io.open(RECIPES, encoding='utf-8'), object_pairs_hook=OD)
    C = json.load(io.open(CMAP, encoding='utf-8'))
    V = json.load(io.open(VERIFY, encoding='utf-8'))
    P = json.load(io.open(PRICE, encoding='utf-8'))
    names = {it['id']: it['n'] for g in P['групи'] for it in g['items']}

    if 'штатна_поведінка' not in R['шаблони']:
        R['шаблони']['штатна_поведінка'] = TEMPLATE

    have = set()
    for pid, lvs in R['позиції'].items():
        for lk, items in lvs.items():
            for t in items:
                have.add((pid, lk, t))

    added, skipped = [], 0
    for pid, blk in C['позиції'].items():
        for lk in ('1', '2', '3'):
            for r in blk.get('рівні', {}).get(lk, []):
                key = (pid, lk, r['пункт'])
                if key in have:
                    skipped += 1
                    continue
                st = (V['позиції'][pid][lk]['пункти'] or {})[r['пункт']]
                z = st.get('звірка') or {}
                if rg.kind(r['моделі'], z.get('є'), pid, r.get('модулі')) != 'штатна поведінка':
                    continue
                R['позиції'].setdefault(pid, OD()).setdefault(lk, OD())
                R['позиції'][pid][lk][r['пункт']] = OD([
                    ('кроки', [OD([
                        ('дія', 'шаблон'), ('назва', 'штатна_поведінка'),
                        ('аргументи', OD([
                            ('моделі', r['моделі']),
                            ('що_показати', 'показати клієнтові на живих документах: %s'
                                            % r['пункт']),
                        ]))])]),
                    ('джерело', 'згенеровано із карти налаштування '
                                '(tools/gen_standard_recipes.py) — вид «штатна поведінка», '
                                'конфігурації в пункті немає'),
                    ('увага', 'подробиці того, що саме показувати, — у журналі перевірки '
                              '(docs/журнал-налаштування-edu-online-todo.md, позиція «%s» '
                              'рівень %s): там записано, на яких документах це перевірялося'
                              % (names[pid], lk)),
                ])
                added.append('%s р.%s %s' % (pid, lk, r['пункт']))

    if '--dry' in argv:
        print('додало б рецептів: %d (наявних не чіпає: %d)' % (len(added), skipped))
        for a in added[:10]:
            print('   ', a)
        return 0

    io.open(RECIPES, 'w', encoding='utf-8').write(
        json.dumps(R, ensure_ascii=False, indent=1) + '\n')
    print('OK: додано %d рецептів виду «штатна поведінка», наявних не чіпало %d'
          % (len(added), skipped))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
