# -*- coding: utf-8 -*-
"""Бриф на демо: що саме менеджер збирається показувати і наскільки повно.

Крок стоїть ПЕРЕД збіркою бази й існує з однієї причини: без нього збирається
весь куплений набір на максимальну глибину, а на демо менеджер показує три
позиції з двадцяти. Решта — робота, яку ніхто не побачить, і питання клієнту,
на які він відповідав дарма.

Тому інструмент не вгадує, а питає:

  1. які позиції справді будуть на екрані («показуємо»);
  2. наскільки повні дані потрібні («повнота»).

Три рівні повноти, і кожен змінює ДВІ речі — скільки питають у клієнта і
скільки демо-записів заводять:

  зібране     — збираємо з того, що вже є в анкеті й діагностиці. Нічого не
                питаємо додатково. Кроки без даних пропускаються, і план
                називає кожен пропущений. Демо показує налаштування, не дані.
  уточнене    — те саме, плюс план друкує КОРОТКИЙ перелік того, чого бракує,
                щоб демо не виглядало порожнім. Менеджер питає це в клієнта,
                дозаповнює профіль і перезапускає план.
  максимальне — план не видається, поки заповнені не всі поля. Найдовше на
                підготовку, найбагатше демо.

Відповідь живе в профілі клієнта, у блоці «демо», і її читає емітер.

Запуск:
    python3 tools/demo_brief.py data/client-profile-example.json
"""

import io
import json
import sys

PRICE = 'data/price.json'


def позиції_прайсу():
    price = json.load(io.open(PRICE, encoding='utf-8'))
    names, q = {}, {}
    for g in price['групи']:
        for it in g['items']:
            names[it['id']] = it['n']
            q[it['id']] = it.get('q', '')
    return names, q


def анкета(prof, names, q):
    """Питання менеджеру. Друкується, поки на нього не відповіли."""
    набір = prof.get('набір') or {}
    print('# Бриф на демо — %s' % prof.get('назва', '(без назви)'))
    print()
    print('Перед збіркою треба два рішення менеджера. Поки їх немає, збирати')
    print('довелося б увесь набір на максимум — це %d позицій, і більшість із них'
          % len(набір))
    print('на демо ніхто не відкриє.')
    print()
    print('## 1. Що показуємо на екрані')
    print()
    print('Лишити в переліку тільки те, що справді буде в демонстрації:')
    print()
    for pid, lv in набір.items():
        print('- `%s` — %s, рівень %s%s'
              % (pid, names.get(pid, pid), lv,
                 (' · питання сейла: %s' % q[pid]) if q.get(pid) else ''))
    print()
    print('## 2. Наскільки повні дані')
    print()
    print('| Рівень | Що питаємо в клієнта | Що на демо | Коли брати |')
    print('|---|---|---|---|')
    print('| `зібране` | нічого понад анкету | налаштування без даних | '
          'демо швидке, клієнт уже втомився від питань |')
    print('| `уточнене` | короткий перелік, який назве план | живі приклади '
          'у показаних позиціях | типовий випадок |')
    print('| `максимальне` | усе, поки профіль не повний | повний цикл із '
          'документами | великий клієнт, рішення за столом |')
    print()
    print('## Відповідь')
    print()
    print('Додати в профіль клієнта блок і перезапустити цей бриф:')
    print()
    print('```json')
    print(json.dumps({'демо': {'повнота': 'уточнене',
                              'показуємо': list(набір)[:3],
                              'записів_на_позицію': 3}},
                     ensure_ascii=False, indent=1))
    print('```')
    print()
    print('`показуємо: []` означає «усі куплені позиції» — це законно, але це')
    print('рішення, а не замовчування: так пишуть тоді, коли демо справді по всьому')
    print('набору.')


def підсумок(prof, demo, names):
    набір = prof.get('набір') or {}
    показ = demo['показуємо'] or list(набір)
    print('# Бриф на демо — %s' % prof.get('назва', '(без назви)'))
    print()
    print('Повнота: **%s** · демо-записів на позицію: %s'
          % (demo['повнота'], demo['записів']))
    print()
    print('## Збираємо (%d з %d позицій набору)' % (len(показ), len(набір)))
    print()
    for pid in показ:
        print('- %s, рівень %s' % (names.get(pid, pid), набір.get(pid, '?')))
    решта = [p for p in набір if p not in показ]
    if решта:
        print()
        print('## Не збираємо — на демо не показуємо')
        print()
        print('Куплено, але в цю збірку не входить: %s.'
              % ', '.join(names.get(p, p) for p in решта))
        print('Це рішення менеджера, а не пропуск: перед запуском бази клієнта')
        print('збірку роблять на весь набір.')
    print()
    print('## Далі')
    print()
    print('    python3 tools/emit_config_calls.py <профіль> ')
    print()
    if demo['повнота'] == 'зібране':
        print('План назве кроки, які пропустив через брак даних, — перечитати цей')
        print('перелік перед демо, щоб не обіцяти клієнту того, чого в базі немає.')
    elif demo['повнота'] == 'уточнене':
        print('План надрукує короткий перелік того, що спитати в клієнта. Питання')
        print('ставляться ОДИН раз: відповіді вносяться в профіль, план перезапускається.')
    else:
        print('План не складеться, поки в профілі лишається незаповнене поле, —')
        print('це і є сенс рівня «максимальне».')


def main(argv):
    if len(argv) < 2:
        print('вжиток: python3 tools/demo_brief.py <профіль.json>')
        return 2
    prof = json.load(io.open(argv[1], encoding='utf-8'))
    names, q = позиції_прайсу()

    d = prof.get('демо') or {}
    if not d.get('повнота'):
        анкета(prof, names, q)
        print()
        print('— менеджер ще не відповів: блока «демо» в профілі немає.')
        return 2

    # правила ті самі, що в емітера, і читаються з нього — щоб «повнота» не
    # означала в брифі одне, а в плані інше
    sys.path.insert(0, 'tools')
    import importlib.util
    spec = importlib.util.spec_from_file_location('emit', 'tools/emit_config_calls.py')
    emit = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(emit)
    demo = emit.демо_налаштування(prof, prof.get('набір') or {})
    підсумок(prof, demo, names)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
