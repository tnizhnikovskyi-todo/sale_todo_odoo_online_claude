# -*- coding: utf-8 -*-
"""Звіряє похідні числа в CLAUDE.md із даними.

Навіщо саме цей файл. CLAUDE.md — не документація «на потім», а **інструкція,
яку читає кожна наступна сесія перед першою дією**. Якщо його числа застаріли,
робота починається з хибних фактів: «314 пунктів мають адресу» замість 324,
«842 кроки» замість 870, «21 натискання» замість 26.

10.09.2026 таких чисел знайшлося **девʼять**, і частину зістарив я сам того ж
дня: додав поле в анкету — «115 полів» стало неправдою; додав тести — «21
натискання» стало неправдою. Тобто це не колишня недбалість, а **клас, який
відтворюється щоразу**, коли правиш дані й не перечитуєш інструкцію.

Правило добору: перевіряються тільки ті числа, у яких є **однозначне джерело в
даних**. Гіпотези (години, економія, ставки), числа з живої бази (моделі з
властивостями, зовнішні id) і кількості, які залежать від набору, тут не
перевіряються — вони або в інших перевірках, або їх не можна порахувати з
репозиторію.

Запуск: python3 tools/check_claude_md.py
"""
import io
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MD = os.path.join(ROOT, 'CLAUDE.md')
# Другий документ під тим самим правилом. `docs/відкриті-питання.md` наступна
# сесія читає одразу після CLAUDE.md — і 10.09.2026 у ньому знайшлися три
# застарілі числа («39 пунктів описано, 321 лишилося» замість 360 і 0; гарантія
# «10 робочих днів» замість 15). Одне з них зістарив той самий прохід, який
# закрив рецепти: класична друга копія знання.
OPEN = os.path.join(ROOT, 'docs', 'відкриті-питання.md')


def дані():
    """Порахувати з джерел усе, що потім шукається в тексті."""
    ч = {}
    price = json.load(io.open(os.path.join(ROOT, 'data', 'price.json'), encoding='utf-8'))
    поз = [it for g in price['групи'] for it in g['items']]
    ч['позицій'] = len(поз)
    ч['рівнів'] = sum(len(it['lv']) for it in поз)
    ч['пунктів'] = (sum(len(it.get('inc', [])) for it in поз)
                    + sum(len(l[4]) for it in поз for l in it['lv']))
    ч['ознак'] = ч['рівнів']
    ч['bounds'] = sum(len(it.get('bounds', [])) for it in поз)
    ч['рядків_довідника'] = ч['пунктів'] + ч['ознак'] + ч['bounds']

    qual = json.load(io.open(os.path.join(ROOT, 'data', 'qualification.json'), encoding='utf-8'))
    скр = [b for b in qual['блоки'] if b['id'] == 'scr'][0]
    ч['гейтів'] = len(скр['питання'])
    ч['глибина'] = sum(len(v) for v in qual['глибина'].values())

    form = json.load(io.open(os.path.join(ROOT, 'data', 'client-form.json'), encoding='utf-8'))
    ч['полів_постійних'] = (sum(len(r['поля']) for r in form['розділи'])
                            + sum(len(r['поля']) for r in form['розділи2']))
    ч['блоків_процесів'] = len(form['процеси'])
    ч['питань_процесів'] = sum(len(p['питання']) for p in form['процеси'])
    ч['полів_анкети'] = ч['полів_постійних'] + ч['питань_процесів']

    vr = json.load(io.open(os.path.join(ROOT, 'data', 'verify.json'), encoding='utf-8'))
    записи = [r for lvs in vr['позиції'].values() for b in lvs.values()
              for r in b['пункти'].values()]
    ч['звірка_всього'] = len(записи)
    ч['звірка_є'] = sum(1 for r in записи if (r.get('звірка') or {}).get('є'))
    ч['звірка_немає'] = ч['звірка_всього'] - ч['звірка_є']

    cm = json.load(io.open(os.path.join(ROOT, 'data', 'config-map.json'), encoding='utf-8'))
    зв = cm['зведення']
    ч['карта_з_адресою'] = зв['з моделями']
    ч['карта_без_адреси'] = зв['без машинної адреси']
    ч['карта_моделей'] = зв['різних моделей']

    rec = json.load(io.open(os.path.join(ROOT, 'data', 'recipes.json'), encoding='utf-8'))
    рецепти = [x for lvs in rec['позиції'].values() for items in lvs.values()
               for x in items.values()]
    ч['рецептів'] = len(рецепти)
    ч['згенерованих'] = sum(1 for x in рецепти if x.get('джерело'))
    ч['рукописних'] = ч['рецептів'] - ч['згенерованих']
    ч['кроків_рецептів'] = sum(len(x.get('кроки', [])) for x in рецепти)
    ч['шаблонів'] = len([k for k in rec['шаблони'] if not k.startswith('_')])
    ч['рецептів_лишилось'] = ч['пунктів'] - ч['рецептів']

    проф = json.load(io.open(os.path.join(ROOT, 'data', 'client-profile-example.json'),
                             encoding='utf-8'))
    ч['профіль_позицій'] = len(проф['набір'])

    # Строки гарантії живуть у фіксованому тексті КП — там вони й правляться, і
    # `build_calculator.py` перевіряє, що 5 + 10 = 15. Тут перевіряється друге:
    # що документ переказує ті самі числа, а не свою пам'ять про них.
    calc = io.open(os.path.join(ROOT, 'artifacts', 'calculator.html'), encoding='utf-8').read()
    for ключ, рег in [('гарантія_днів', r'Супровід запуску — (\d+) робочих днів'),
                      ('зауваження_днів', r'(\d+) робочих днів на зауваження'),
                      ('дефекти_днів', r'протягом (\d+) робочих днів після приймання')]:
        m = re.search(рег, calc)
        ч[ключ] = int(m.group(1)) if m else None
    return ч


def з_емітера(*прапорці):
    """Кроки й виклики плану — рахує сам емітер, а не ми.

    Без прапорців — набір профілю-прикладу (22 позиції), з «--всі» — весь прайс
    рівня 3. Обидва числа названі в документах, і обидва зростають від правки
    рецептів, тому обидва треба питати в емітера, а не пам'ятати.
    """
    r = subprocess.run(['python3', os.path.join('tools', 'emit_config_calls.py'),
                        os.path.join('data', 'client-profile-example.json')]
                       + list(прапорці),
                       capture_output=True, text=True, cwd=ROOT)
    if r.returncode != 0:
        return None, None
    m = re.search(r'Кроків до виконання: (\d+) · викликів конектора: (\d+)', r.stdout)
    return (int(m.group(1)), int(m.group(2))) if m else (None, None)


# Кількість перевірок у браузерному тесті тут НЕ перевіряється, і це не недогляд:
# частина `ok(...)` стоїть у циклах, тому підрахунок у коді дає 24, а прогін —
# 26. Це властивість ПРОГОНУ, а не джерела; правильне місце для неї — останній
# рядок самого тесту («пройшло 26 із 26»), який видно в `check_all.py`.


def main():
    ч = дані()
    ч['кроків_плану'], ч['викликів'] = з_емітера('--всі')
    ч['профіль_кроків'], ч['профіль_викликів'] = з_емітера()

    # Кожне твердження — регулярка з ОДНІЄЮ групою-числом і ключ у «ч».
    # Прив’язка до сусіднього тексту навмисно довга: те саме число трапляється
    # в документі кілька разів, і без прив’язки перевірка сварилася б не на те.
    ТВЕРДЖЕННЯ = [
        (r'карта налаштування \(генерується\): (\d+) із 360 пунктів мають адресу',
         'карта_з_адресою', 'адрес у карті налаштування'),
        (r'Адресу мають\s+\*\*(\d+) пункт\w*\*\*', 'карта_з_адресою',
         'адрес у карті (розділ інструментарію)'),
        (r'решта (\d+) — послуги й дії інтерфейсу', 'карта_без_адреси',
         'пунктів без адреси'),
        (r'Перелік із (\d+) моделей \*\*звірений', 'карта_моделей',
         'різних моделей у карті'),
        (r'фільтрує по всіх (\d+) рядках', 'рядків_довідника',
         'рядків у довіднику четвертої сторінки'),
        (r'\+ (\d+) рядків «не входить»\)', 'bounds', 'рядків «не входить»'),
        (r'що ще — (\d+) пол\w+\.', 'полів_постійних', 'постійних полів анкети'),
        (r'\*\*Блоки процесів\*\* \((\d+)\)', 'блоків_процесів', 'блоків процесів анкети'),
        (r'потрібно: (\d+) питанн\w+ його мовою', 'питань_процесів',
         'питань у блоках процесів'),
        (r'\*\*Скринінг\*\* — (\d+) питан\w+-гейт', 'гейтів', 'гейтів скринінгу'),
        (r'банк питань на (\d+) позиці', 'глибина', 'питань у банку глибини'),
        (r'\*\*(\d+) із 360 знайдено в базі, (?:\d+) немає\*\*', 'звірка_є',
         'знайдено в базі'),
        (r'із 360 знайдено в базі, (\d+) немає', 'звірка_немає', 'не знайдено в базі'),
        (r'\*\*(\d+) із 360 описано\*\* \((?:\d+) рукописних', 'рецептів',
         'описано рецептами'),
        (r'описано\*\* \((\d+) рукописних', 'рукописних', 'рукописних рецептів'),
        (r'рукописних, (\d+) згенерованих\)', 'згенерованих', 'згенерованих рецептів'),
        (r'360 пунктів із 360, (\d+) крок\w*\.\*\*', 'кроків_рецептів',
         'кроків у рецептах'),
        (r'План на весь прайс рівня 3 — ([\d\s ]+) кроків', 'кроків_плану',
         'кроків у повному плані'),
        (r'кроків і ([\d\s ]+) викликів конектора', 'викликів',
         'викликів конектора в повному плані'),
        # Скільки чисел перевіряється — теж число в CLAUDE.md, і без цього рядка
        # воно єдине лишалося б без сторожа: додав твердження, забув переписати
        # інструкцію. Джерело — довжина самих переліків нижче.
        # Форма слова залежить від самого числа — 29 «чисел», 31 «число», — тому
        # в регулярці `чис\w+`, а не одна форма: перша версія вимагала «чисел» і
        # зламалась на тому самому кроці, який її додав.
        (r'звіряє похідні числа з даними: CLAUDE.md і відкриті питання \((\d+) чис\w+\)',
         'тверджень', 'кількість перевірених чисел (структура)'),
        (r'перевіряє \*\*(\d+) чис\w+\*\* із', 'тверджень',
         'кількість перевірених чисел (розділ про числа)'),
    ]
    # Значення, яких може не бути з причини, про яку скаже інша перевірка
    # (емітер не запустився). Усе інше відсутнє = поломка саме тут.
    МОЖНА_БЕЗ = ('кроків_плану', 'викликів', 'профіль_кроків', 'профіль_викликів')
    # `docs/відкриті-питання.md`: числа, у яких є однозначне джерело. Строки
    # гарантії беруться з фіксованого тексту КП — документ мусить переказувати
    # його, а не свою пам'ять (10.09.2026 переказував «10 днів» проти 15 у КП).
    ТВЕРДЖЕННЯ_ВІДКРИТІ = [
        (r'\*\*(\d+) пунктів описано, (?:\d+) лишилося\*\*', 'рецептів',
         'описано рецептами'),
        (r'пунктів описано, (\d+) лишилося\*\*', 'рецептів_лишилось',
         'пунктів без рецепта'),
        (r'\((\d+) рукописних рецепт\w+', 'рукописних', 'рукописних рецептів'),
        (r'рукописних рецептів і (\d+) згенерован\w+', 'згенерованих',
         'згенерованих рецептів'),
        (r'набір із (\d+) позицій рівня 3', 'профіль_позицій',
         'позицій у наборі профілю-прикладу'),
        (r'позицій рівня 3 — ([\d\s\u00a0\u202f]+) кроків', 'профіль_кроків',
         'кроків у плані профілю'),
        (r'кроків і ([\d\s\u00a0\u202f]+) викликів\s*\(≈', 'профіль_викликів',
         'викликів у плані профілю'),
        (r'\*\*(\d+) робочих днів від демонстрації позиції\*\*', 'гарантія_днів',
         'гарантійне вікно (проти КП)'),
        (r'\((\d+) на зауваження \+ (?:\d+) на дефекти\)', 'зауваження_днів',
         'днів на зауваження (проти КП)'),
        (r'на зауваження \+ (\d+) на дефекти\)', 'дефекти_днів',
         'днів на дефекти (проти КП)'),
    ]

    ч['тверджень'] = len(ТВЕРДЖЕННЯ) + len(ТВЕРДЖЕННЯ_ВІДКРИТІ)
    errs, перевірено = [], 0
    for шлях, назва, твердження in [(MD, 'CLAUDE.md', ТВЕРДЖЕННЯ),
                                    (OPEN, 'відкриті питання', ТВЕРДЖЕННЯ_ВІДКРИТІ)]:
        текст = io.open(шлях, encoding='utf-8').read()
        for рег, ключ, підпис in твердження:
            m = re.search(рег, текст)
            if not m:
                errs.append('твердження про %s у %s не знайдено — регулярку або текст '
                            'змінили, і перевірка перестала дивитися на нього'
                            % (підпис, назва))
                continue
            якщо = ч.get(ключ)
            if якщо is None:
                if ключ not in МОЖНА_БЕЗ:
                    errs.append('%s: %s — нема з чим звіряти, джерело числа зникло'
                                % (назва, підпис))
                continue
            сказано = int(re.sub(r'[^\d]', '', m.group(1)))
            перевірено += 1
            if сказано != якщо:
                errs.append('%s: %s — сказано %d, а в даних %d'
                            % (назва, підпис, сказано, якщо))
    for e in errs:
        print('  • %s' % e)
    if errs:
        print('ПОМИЛКА: документи розійшлися з даними (%d)' % len(errs))
        return 1
    print('OK: CLAUDE.md і відкриті питання — %d похідних чисел збігаються з даними'
          % перевірено)
    return 0


if __name__ == '__main__':
    sys.exit(main())
