# -*- coding: utf-8 -*-
"""Звіряє artifacts/concept.html з прайсом і з чинними рішеннями.

Навіщо. Концепція — не згенерований файл: її правлять руками, і вона живе довше
за будь-яке окреме рішення. Тому вона тихо застаріває. 10.09.2026 виявилося, що
вона **двадцять разів** називає Studio нашим способом впровадження — через рік
після того, як від Studio відмовилися (рішення 09.09.2026, усі 45 пунктів прайсу
переведені на штатні шляхи). Той самий клас, що застарілий артефакт аналізу:
опублікований документ описує роботу, якої ми не робимо.

Що перевіряється:

1. **Числа.** Кожен рядок таблиці, який називає позицію прайсу, мусить збігатися
   з `data/price.json` — і за ціною, і за годинами.

   Рядки наборів («Торгівля», «Проєктний бізнес») позицією не є, і для них
   перевіряється ЛИШЕ власна арифметика: `ціна = години × 50` і
   `маржа = ціна − собівартість`. Спокуса перерахувати набір із його складу
   велика — і **двічі за один прохід дала хибну тривогу**: спершу я взяв усі
   позиції на рівні 2 (насправді обов'язкові «Рахунки та оплати» приходять
   жорсткою залежністю на рівні 1), потім не помітив, що «Продажі» в сервісному
   й проєктному наборах теж залежність, а не вибір, — рівно ті 8 годин різниці.
   Обидва правила написані у виносці ПІД таблицею, яку я не прочитав перед тим,
   як рахувати. Тому перевірка навмисно вужча за спокусу: сума набору залежить
   від бізнес-логіки залежностей, а не від даних, і хибна тривога тут гірша за
   відсутність перевірки.
2. **Стоп-слова рішень.** Теми, зняті з контуру, у концепції не з’являються
   взагалі: ПРРО, КЕП, фіскалізація, «Рахунки та податки».
3. **Studio.** Слово дозволене ЛИШЕ в запереченні («не відкриваємо», «без
   Studio», «ні в Studio»). Згадка без заперечення означає, що документ знову
   продає спосіб, від якого відмовилися.

Запуск: python3 tools/check_concept.py
"""
import io
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HTML = os.path.join(ROOT, 'artifacts', 'concept.html')
PRICE = os.path.join(ROOT, 'data', 'price.json')
RATE = 50

# Теми, зняті з контуру рішеннями 05.09 і 09.09. У концепції їх не буває взагалі:
# на відміну від «обліку» чи «податків», ці слова не мають законного вжитку навіть
# у запереченні — межа сформульована інакше («облік у базі не ведемо»).
СТОП = ['ПРРО', 'КЕП', 'фіскаліз', 'Рахунки та податки']
# Studio дозволена лише в запереченні. Перелік — не здогад: це формулювання, які
# у документі стоять сьогодні.
STUDIO_OK = ['не відкриваємо', 'без Studio', 'ні в Studio']


def чис(t):
    for x in (' ', ' ', ' ', ' '):
        t = t.replace(x, '')
    return int(t)


def ціни(it):
    return [(l[1], int(round(l[1] * RATE / 50.0) * 50)) for l in it['lv']]


def main():
    html = io.open(HTML, encoding='utf-8').read()
    price = json.load(io.open(PRICE, encoding='utf-8'))
    поз = {it['n']: it for g in price['групи'] for it in g['items']}
    errs = []

    # 1а. таблиця прайсу: назва | опис | €ціна
    rx1 = re.compile(r'<tr><td>([^<]+)</td><td>[^<]*</td><td class="num">€([\d\s  ]+)</td></tr>')
    n1 = 0
    for назва, ц in rx1.findall(html):
        it = поз.get(назва.strip())
        if not it:
            continue          # рядок не про позицію прайсу
        n1 += 1
        if чис(ц) not in [c for _, c in ціни(it)]:
            errs.append('таблиця прайсу: «%s» — €%s, а в прайсі %s'
                        % (назва, чис(ц), [c for _, c in ціни(it)]))

    # 1б. таблиця економіки: назва | години | години з інстр. | €собівартість | €ціна
    # «%» наприкінці — ознака таблиці ПОЗИЦІЙ. Без неї той самий шаблон ловить і
    # таблицю наборів, у якої колонки інші (Позицій | Год | Ціна | Собів. | Маржа),
    # і перевірка починає порівнювати кількість позицій із годинами. Спіймано на собі.
    # Рядок може бути й підсумковим (class="total"), а додатна маржа фарбується
    # класом «pos» — обидві дрібниці ловилися на собі: строгий шаблон мовчки
    # пропускав три позиції з пʼятнадцяти, і перевірка виглядала пройденою.
    # «%%» наприкінці лишається обовʼязковим: це ознака таблиці ПОЗИЦІЙ, без неї
    # той самий шаблон ловить і таблицю наборів з іншими колонками.
    rx2 = re.compile(r'<tr(?: class="total")?><td>([^<]+)</td><td class="num">(\d+)</td><td class="num">(\d+)</td>'
                     r'<td class="num">€([\d\s  ]+)</td><td class="num">€([\d\s  ]+)</td>'
                     r'<td class="num(?: pos)?">€[\d\s  ]+</td><td class="num">\d+%</td>')
    n2 = 0
    for назва, год, _зг, _соб, ц in rx2.findall(html):
        назва, год, ц = назва.strip(), int(год), чис(ц)
        n2 += 1
        it = поз.get(назва)
        if it:
            if (год, ц) not in ціни(it):
                errs.append('таблиця економіки: «%s» — %d год / €%d, а в прайсі %s'
                            % (назва, год, ц, ціни(it)))
        else:
            errs.append('таблиця економіки: рядок «%s» не є позицією прайсу' % назва)

    # 1в. таблиця наборів: Профіль | Позицій | Год вручну | Ціна | Собів. | Маржа
    rx3 = re.compile(r'<tr(?: class="total")?><td>([^<]+)</td>'
                     r'<td class="num">(\d+)</td><td class="num">(\d+)</td>'
                     r'<td class="num">€([\d\s  ]+)</td><td class="num">€([\d\s  ]+)</td>'
                     r'<td class="num(?: pos)?">€([\d\s  ]+)</td></tr>')
    n3 = 0
    for назва, _поз, год, ц, соб, маржа in rx3.findall(html):
        n3 += 1
        год, ц, соб, маржа = int(год), чис(ц), чис(соб), чис(маржа)
        очік = int(round(год * RATE / 50.0) * 50)
        if ц != очік:
            errs.append('набір «%s»: %d год × €%d = €%d, а стоїть €%d'
                        % (назва, год, RATE, очік, ц))
        if ц - соб != маржа:
            errs.append('набір «%s»: €%d − €%d = €%d, а маржа стоїть €%d'
                        % (назва, ц, соб, ц - соб, маржа))

    # 2. стоп-слова знятих тем
    for w in СТОП:
        if w.lower() in html.lower():
            errs.append('слово «%s» у концепції: тему знято з контуру, у документі '
                        'її не буває навіть у запереченні' % w)

    # 3. Studio лише в запереченні
    for m in re.finditer(r'Studio', html):
        вікно = html[max(0, m.start() - 160):m.end() + 160]
        if not any(x in вікно for x in STUDIO_OK):
            errs.append('«Studio» без заперечення (позиція %d): «…%s…»'
                        % (m.start(), re.sub(r'<[^>]+>', '', вікно)[80:200].strip()))

    for e in errs:
        print('  • %s' % e)
    if errs:
        print('ПОМИЛКА: концепція розійшлася з прайсом або з рішеннями (%d)' % len(errs))
        return 1
    print('OK: концепція — %d рядків прайсу, %d позицій економіки, %d наборів, '
          'стоп-слів немає' % (n1, n2, n3))
    return 0


if __name__ == '__main__':
    sys.exit(main())
