"""Збирає docs/рецепти-що-лишилось.md — що ще треба описати рецептами.

Навіщо окремий звіт, а не автогенерація. Спокуса згенерувати рецепти для всіх
360 пунктів велика: шаблони є, моделі відомі з карти налаштування. Але склад
полів у поданні, домен фільтра й значення полів вигадати неможливо — вони
залежать від того, як працює конкретний клієнт. Автогенерація дала б
правдоподібні й неправильні рецепти, а це найгірший результат: їх ніхто не
перевірить, бо вони «вже є».

Тому скрипт не пише рецептів. Він каже, **де вони потрібні і який шаблон
підходить** — за моделями з карти налаштування:

* `ir.ui.view` + `ir.actions.act_window` + `ir.ui.menu` → шаблон `робоче_місце`
* `ir.model.fields` (+ `ir.ui.view`)                    → шаблон `власне_поле`
* `ir.actions.server`                                   → один із шаблонів кнопок
* решта                                                 → писати руками

Запуск: python3 tools/report_recipe_gaps.py
"""

import collections
import io
import json
import sys

PRICE = 'data/price.json'
CMAP = 'data/config-map.json'
RECIPES = 'data/recipes.json'
VERIFY = 'data/verify.json'
OUT = 'docs/рецепти-що-лишилось.md'


# ── Вид роботи ────────────────────────────────────────────────────────────────
# Прогін кластера sale.order показав головне: пункти однієї моделі — це часто ТРИ
# різні види роботи. Ділити залишок за моделлю тому мало: модель каже, де це лежить,
# а трудомісткість і сама потреба в рецепті залежать від виду.
#
# Правило навмисно просте й переглядне, бо будь-яка розумніша евристика тут бреше:
#
#   немає моделей або звірка кажe «в базі цього не буває» → ПОСЛУГА
#   головні моделі — тільки документи (DOCS)                → ШТАТНА ПОВЕДІНКА
#   решта                                                    → КОНФІГУРАЦІЯ
#
# Перелічені саме ДОКУМЕНТИ, а не налаштування: список документів менший, стабільніший
# і його легко переглянути очима. Усе неперелічене вважається конфігурацією — це
# безпечніший бік помилки: «є що описати» замість «описувати нічого».
#
# ВИД — ПІДКАЗКА, А НЕ ВЕРДИКТ. Один пункт може містити і те, і те (напр. «бронювання
# наперед» пише поля компанії, а сам процес штатний). Якщо вид неправильний — правити
# треба цей перелік, а не звіт.
DOCS = {
    # продажі й закупівлі
    'sale.order', 'sale.order.line', 'sale.report', 'sale.advance.payment.inv',
    'purchase.order', 'purchase.order.line', 'purchase.report',
    # гроші
    'account.move', 'account.move.line', 'account.payment', 'account.payment.register',
    'account.bank.statement', 'account.bank.statement.line',
    # склад і виробництво
    'stock.picking', 'stock.move', 'stock.move.line', 'stock.quant', 'stock.scrap',
    'stock.inventory.conflict', 'mrp.production', 'mrp.workorder', 'mrp.unbuild',
    # проєкти, сервіс, персонал
    'project.task', 'crm.lead', 'helpdesk.ticket', 'maintenance.request',
    'planning.slot', 'hr.leave', 'hr.expense', 'hr.attendance', 'approval.request',
    'calendar.event', 'sign.request', 'pos.order', 'pos.session', 'repair.order',
    'account.analytic.line',
}


# «Експрес-діагностика» — єдина позиція прайсу, чиї артефакти лежать не в базі
# клієнта, а в нашому ж калькуляторі: питання скринінгу, банк питань на глибину,
# кнопки КП і нотаток. Рецепта для «розмови про поточний процес» не буде ніколи,
# тому ці 11 пунктів не мають потрапляти в жоден вид роботи в базі.
NOT_IN_BASE = {'diag'}


def kind(models, audit_has, pid=None, modules=None):
    """Вид роботи за пунктом: послуга / штатна поведінка / конфігурація / без адреси.

    Перша версія цього правила вважала послугою будь-який пункт без моделей — і на
    вибірці відразу збрехала: «автоматичні активності за стадіями» це створене правило
    автоматизації (перевірене ділом), а не послуга. Просто в карті налаштування для
    нього немає адреси.

    Тому **відсутність даних більше не вважається даними**. Послуга — це те, про що
    звірка сказала «в базі такого не буває» (`є: false`). Пункт без адреси йде в окремий
    вид: він означає роботу в карті, а не вид роботи в базі.
    """
    if pid in NOT_IN_BASE:
        return 'не в базі: інструмент сейла'
    if audit_has is False:
        return 'послуга'
    if not models:
        # Пункт, у якого адреса — МОДУЛЬ, а не модель: «застосунок data_cleaning»,
        # «worksheet + industry_fsm_report», «spreadsheet_dashboard_edition —
        # установлений». Такий пункт не «без адреси»: адреса в нього найконкретніша —
        # щоб він працював, модуль має бути в базі. Робота ж тут конфігураційна:
        # переконатися, що застосунок стоїть, і налаштувати те, що він приносить.
        if modules:
            return 'конфігурація'
        return 'без адреси в карті'
    if all(m in DOCS for m in models):
        return 'штатна поведінка'
    return 'конфігурація'


def guess(models, txt=''):
    s = set(models)
    # кнопки визначаємо за текстом пункту: у них часто є і поле-ознака, і дія сервера,
    # тому за самими моделями «власне_поле» переможе помилково
    if txt.lstrip().startswith('кнопк') and 'ir.actions.server' in s:
        return 'кнопка_ознака / кнопка_стадія / кнопка_завдання'
    if {'ir.ui.view', 'ir.actions.act_window', 'ir.ui.menu'} <= s:
        return 'робоче_місце'
    if {'ir.ui.view', 'ir.actions.act_window'} <= s or {'ir.actions.act_window', 'ir.ui.menu'} <= s:
        return 'робоче_місце (неповний набір моделей — звірити з журналом)'
    if 'ir.model.fields' in s:
        return 'власне_поле'
    if 'ir.actions.server' in s:
        return 'кнопка_ознака / кнопка_стадія / кнопка_завдання'
    if 'base.automation' in s:
        return 'руками: правило автоматизації'
    if 'ir.rule' in s:
        return 'руками: правило записів'
    if not s:
        return 'нема адреси — послуга або дія інтерфейсу'
    return 'руками'


def main():
    price = json.load(io.open(PRICE, encoding='utf-8'))
    cmap = json.load(io.open(CMAP, encoding='utf-8'))
    rec = json.load(io.open(RECIPES, encoding='utf-8'))

    have = set()
    generated = set()
    for pid, levels in rec['позиції'].items():
        for lk, items in levels.items():
            for txt, body in items.items():
                have.add((pid, lk, txt))
                # Рецепти виду «штатна поведінка» дописує генератор
                # (tools/gen_standard_recipes.py). Рахувати їх разом із рукописними
                # означало б завищувати готовність: у них немає конфігурації, тільки
                # перевірка застосунку й показ процесу.
                if isinstance(body, dict) and body.get('джерело'):
                    generated.add((pid, lk, txt))

    names = {}
    order = []
    for g in price['групи']:
        for it in g['items']:
            names[it['id']] = it['n']
            order.append(it['id'])

    vrfy = json.load(io.open(VERIFY, encoding='utf-8'))
    rows = []
    by_tpl = collections.Counter()
    by_model = collections.Counter()
    by_kind = collections.Counter()
    kind_done = collections.Counter()
    done = 0
    for pid in order:
        blk = cmap['позиції'].get(pid, {})
        for lk in ('1', '2', '3'):
            for r in blk.get('рівні', {}).get(lk, []):
                key = (pid, lk, r['пункт'])
                st = ((vrfy['позиції'].get(pid) or {}).get(lk) or {}).get('пункти') or {}
                z = (st.get(r['пункт']) or {}).get('звірка') or {}
                kd = kind(r['моделі'], z.get('є'), pid, r.get('модулі'))
                if key in have:
                    done += 1
                    kind_done[kd] += 1
                    continue
                tpl = guess(r['моделі'], r['пункт'])
                by_tpl[tpl] += 1
                by_kind[kd] += 1
                if tpl == 'руками' and r['моделі']:
                    by_model[r['моделі'][0]] += 1
                rows.append((names[pid], lk, r['пункт'], tpl, r['моделі'], kd))

    L = []
    w = L.append
    w('# Рецепти: що вже є і що лишилося')
    w('')
    w('**Згенеровано** `tools/report_recipe_gaps.py`. Руками не правити.')
    w('')
    w('Це не список задач «на потім», а карта роботи: для кожного пункту без рецепта')
    w('сказано, **який шаблон підходить**. Пункти, позначені «руками», шаблонами не')
    w('закриваються — там треба читати журнал налаштування.')
    w('')
    w('**Чому цей звіт не генерує рецепти сам.** Шаблони є, моделі відомі — спокуса велика.')
    w('Але склад полів у поданні, домен фільтра й значення полів залежать від того, як')
    w('працює конкретний клієнт: вигадати їх не можна. Автогенерація дала б правдоподібні')
    w('й неправильні рецепти, і це найгірший результат — їх ніхто не перевірить, бо вони')
    w('«вже є».')
    w('')
    w('| | |')
    w('|---|---:|')
    w('| Пунктів усього | %d |' % (done + len(rows)))
    w('| Уже описано рецептами | **%d** |' % done)
    w('| з них рукописних | %d |' % (done - len(generated)))
    w('| з них згенерованих (вид «штатна поведінка») | %d |' % len(generated))
    w('| Лишилося | %d |' % len(rows))
    w('')
    w('## Головне: залишок — це різні види роботи, а не один список')
    w('')
    w('Прогін кластера `sale.order` показав, що пункти **однієї моделі** бувають трьома')
    w('різними видами роботи, а після вибірки додалися ще два випадки, які взагалі не є')
    w('роботою в базі. Ділити залишок за моделлю тому недостатньо: модель каже, **де** це')
    w('лежить, а вид визначає **скільки це роботи** і чи потрібен рецепт узагалі.')
    w('')
    w('| Вид роботи | Лишилося | Уже описано | Що робить рецепт |')
    w('|---|---:|---:|---|')
    KOPIS = {
        'конфігурація': 'є що записати: `створити` / `записати` + обовʼязкове `перевірити`',
        'штатна поведінка': 'записувати нічого — `перевірити`, що застосунок став і поля на місці',
        'послуга': 'у базі артефакту не буває (звірка: «є» = ні) — `послуга` з описом',
        'без адреси в карті': 'спершу дописати адресу в карту — вид поки невідомий',
        'не в базі: інструмент сейла': 'рецепта не буде: артефакт у калькуляторі, а не в Odoo',
    }
    for kd in ('конфігурація', 'штатна поведінка', 'послуга', 'без адреси в карті',
               'не в базі: інструмент сейла'):
        w('| %s | %d | %d | %s |' % (kd, by_kind[kd], kind_done[kd], KOPIS[kd]))
    w('')
    w('Вид — **підказка, а не вердикт**. Правило просте: звірка каже «в базі такого не')
    w('буває» → послуга; немає адреси в карті → вид поки невідомий; серед моделей тільки')
    w('документи → штатна поведінка; решта → конфігурація. Один пункт може містити і те,')
    w('і те. Перелік документних моделей стоїть у `tools/report_recipe_gaps.py` — якщо вид')
    w('неправильний, правити треба перелік, а не звіт.')
    w('')
    w('**Чому «без адреси» — окремий вид.** Перша версія правила вважала послугою будь-який')
    w('пункт без моделей і на першій же вибірці збрехала: «автоматичні активності за')
    w('стадіями» — це створене й перевірене ділом правило автоматизації, а не послуга;')
    w('просто в карті для нього немає адреси. Відсутність даних — не дані, і рядок цього')
    w('виду означає роботу **в карті**, а не в базі клієнта.')
    w('')
    w('## Скільки чим закривається')
    w('')
    w('| Шаблон або спосіб | Пунктів |')
    w('|---|---:|')
    for tpl, n in by_tpl.most_common():
        w('| %s | %d |' % (tpl, n))
    w('')
    w('## Де основна робота серед «руками»')
    w('')
    w('Пункти, які шаблонами не закриваються, — це записи в бізнес-моделях: у кожного свої')
    w('поля й значення. Розкладка за головною моделлю показує, з чого починати, щоб один')
    w('раз розібратися в моделі й описати кілька пунктів поряд.')
    w('')
    w('| Головна модель | Пунктів «руками» |')
    w('|---|---:|')
    for m, n in by_model.most_common(15):
        w('| `%s` | %d |' % (m, n))
    w('')
    w('## Скільки це роботи — і чому число тут допущення')
    w('')
    w('Описано **%d** пунктів, лишилося **%d** — приблизно у вісім разів більше за зроблене.'
      % (done, len(rows)))
    w('Шаблонами з них закривається лише кожен десятий: решта — записи в бізнес-моделях, де')
    w('у кожного пункту свої поля й значення.')
    w('')
    w('**Часу на пункт ми не міряли**, тому перекладати це в години тут не будемо: саме')
    w('такий замір — головне число фази 0 (`docs/відкриті-питання.md`). Що можна сказати')
    w('без вигадок: пункти, закриті шаблоном, коштують кількох хвилин, бо в них лишається')
    w('тільки підставити аргументи; пункти «руками» вимагають прочитати журнал і звірити')
    w('поля на базі, і саме вони визначать підсумок.')
    w('')
    w('Практичний висновок для порядку робіт: **починати з моделей, а не з позицій.** Один')
    w('раз розібратися в `sale.order` — і поряд закриваються пункти з кількох різних')
    w('позицій прайсу.')
    w('')
    w('## Перелік')
    w('')
    w('| Позиція | Рівень | Пункт | Вид роботи | Чим закривати | Моделі |')
    w('|---|:--:|---|---|---|---|')
    for pos, lk, txt, tpl, models, kd in rows:
        mm = ', '.join('`%s`' % m for m in models[:3]) or '—'
        w('| %s | %s | %s | %s | %s | %s |' % (pos, lk, txt, kd, tpl, mm))
    w('')

    io.open(OUT, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    print('OK: %s — описано %d (рукописних %d, згенерованих %d), лишилося %d'
          % (OUT, done, done - len(generated), len(generated), len(rows)))
    for kd in ('конфігурація', 'штатна поведінка', 'послуга', 'без адреси в карті',
               'не в базі: інструмент сейла'):
        print('    %-28s лишилося %3d, описано %3d' % (kd, by_kind[kd], kind_done[kd]))
    return 0


if __name__ == '__main__':
    sys.exit(main())
