# -*- coding: utf-8 -*-
"""Збирає docs/рецепти-що-лишилось.md — що ще треба описати рецептами.

Навіщо окремий звіт, а не автогенерація. Спокуса згенерувати рецепти для всіх
360 пунктів велика: шаблони є, моделі відомі з карти налаштування. Але склад
полів у поданні, домен фільтра й значення полів вигадати неможливо — вони
залежать від того, як працює конкретний клієнт. Автогенерація дала б
правдоподібні й неправильні рецепти, а це найгірший результат: їх ніхто не
перевірить, бо вони «вже є».

Тому скрипт не пише рецептів. Він каже, **де вони потрібні і який шаблон
підходить** — за моделями з карти налаштування:

* `ir.ui.view` + `ir.actions.act_window` + `ir.ui.menu` → шаблон `робоче_місце`
* `ir.model.fields` (+ `ir.ui.view`)                    → шаблон `власне_поле`
* `ir.actions.server`                                   → один із шаблонів кнопок
* решта                                                 → писати руками

Запуск: python3 tools/report_recipe_gaps.py
"""

import collections
import io
import json
import sys

PRICE = 'data/price.json'
CMAP = 'data/config-map.json'
RECIPES = 'data/recipes.json'
OUT = 'docs/рецепти-що-лишилось.md'


def guess(models, txt=''):
    s = set(models)
    # кнопки визначаємо за текстом пункту: у них часто є і поле-ознака, і дія сервера,
    # тому за самими моделями «власне_поле» переможе помилково
    if txt.lstrip().startswith('кнопк') and 'ir.actions.server' in s:
        return 'кнопка_ознака / кнопка_стадія / кнопка_завдання'
    if {'ir.ui.view', 'ir.actions.act_window', 'ir.ui.menu'} <= s:
        return 'робоче_місце'
    if {'ir.ui.view', 'ir.actions.act_window'} <= s or {'ir.actions.act_window', 'ir.ui.menu'} <= s:
        return 'робоче_місце (неповний набір моделей — звірити з журналом)'
    if 'ir.model.fields' in s:
        return 'власне_поле'
    if 'ir.actions.server' in s:
        return 'кнопка_ознака / кнопка_стадія / кнопка_завдання'
    if 'base.automation' in s:
        return 'руками: правило автоматизації'
    if 'ir.rule' in s:
        return 'руками: правило записів'
    if not s:
        return 'нема адреси — послуга або дія інтерфейсу'
    return 'руками'


def main():
    price = json.load(io.open(PRICE, encoding='utf-8'))
    cmap = json.load(io.open(CMAP, encoding='utf-8'))
    rec = json.load(io.open(RECIPES, encoding='utf-8'))

    have = set()
    for pid, levels in rec['позиції'].items():
        for lk, items in levels.items():
            for txt in items:
                have.add((pid, lk, txt))

    names = {}
    order = []
    for g in price['групи']:
        for it in g['items']:
            names[it['id']] = it['n']
            order.append(it['id'])

    rows = []
    by_tpl = collections.Counter()
    by_model = collections.Counter()
    done = 0
    for pid in order:
        blk = cmap['позиції'].get(pid, {})
        for lk in ('1', '2', '3'):
            for r in blk.get('рівні', {}).get(lk, []):
                key = (pid, lk, r['пункт'])
                if key in have:
                    done += 1
                    continue
                tpl = guess(r['моделі'], r['пункт'])
                by_tpl[tpl] += 1
                if tpl == 'руками' and r['моделі']:
                    by_model[r['моделі'][0]] += 1
                rows.append((names[pid], lk, r['пункт'], tpl, r['моделі']))

    L = []
    w = L.append
    w('# Рецепти: що вже є і що лишилося')
    w('')
    w('**Згенеровано** `tools/report_recipe_gaps.py`. Руками не правити.')
    w('')
    w('Це не список задач «на потім», а карта роботи: для кожного пункту без рецепта')
    w('сказано, **який шаблон підходить**. Пункти, позначені «руками», шаблонами не')
    w('закриваються — там треба читати журнал налаштування.')
    w('')
    w('**Чому цей звіт не генерує рецепти сам.** Шаблони є, моделі відомі — спокуса велика.')
    w('Але склад полів у поданні, домен фільтра й значення полів залежать від того, як')
    w('працює конкретний клієнт: вигадати їх не можна. Автогенерація дала б правдоподібні')
    w('й неправильні рецепти, і це найгірший результат — їх ніхто не перевірить, бо вони')
    w('«вже є».')
    w('')
    w('| | |')
    w('|---|---:|')
    w('| Пунктів усього | %d |' % (done + len(rows)))
    w('| Уже описано рецептами | **%d** |' % done)
    w('| Лишилося | %d |' % len(rows))
    w('')
    w('## Скільки чим закривається')
    w('')
    w('| Шаблон або спосіб | Пунктів |')
    w('|---|---:|')
    for tpl, n in by_tpl.most_common():
        w('| %s | %d |' % (tpl, n))
    w('')
    w('## Де основна робота серед «руками»')
    w('')
    w('Пункти, які шаблонами не закриваються, — це записи в бізнес-моделях: у кожного свої')
    w('поля й значення. Розкладка за головною моделлю показує, з чого починати, щоб один')
    w('раз розібратися в моделі й описати кілька пунктів поряд.')
    w('')
    w('| Головна модель | Пунктів «руками» |')
    w('|---|---:|')
    for m, n in by_model.most_common(15):
        w('| `%s` | %d |' % (m, n))
    w('')
    w('## Скільки це роботи — і чому число тут допущення')
    w('')
    w('Описано **%d** пунктів, лишилося **%d** — приблизно у вісім разів більше за зроблене.'
      % (done, len(rows)))
    w('Шаблонами з них закривається лише кожен десятий: решта — записи в бізнес-моделях, де')
    w('у кожного пункту свої поля й значення.')
    w('')
    w('**Часу на пункт ми не міряли**, тому перекладати це в години тут не будемо: саме')
    w('такий замір — головне число фази 0 (`docs/відкриті-питання.md`). Що можна сказати')
    w('без вигадок: пункти, закриті шаблоном, коштують кількох хвилин, бо в них лишається')
    w('тільки підставити аргументи; пункти «руками» вимагають прочитати журнал і звірити')
    w('поля на базі, і саме вони визначать підсумок.')
    w('')
    w('Практичний висновок для порядку робіт: **починати з моделей, а не з позицій.** Один')
    w('раз розібратися в `sale.order` — і поряд закриваються пункти з кількох різних')
    w('позицій прайсу.')
    w('')
    w('## Перелік')
    w('')
    w('| Позиція | Рівень | Пункт | Чим закривати | Моделі |')
    w('|---|:--:|---|---|---|')
    for pos, lk, txt, tpl, models in rows:
        mm = ', '.join('`%s`' % m for m in models[:3]) or '—'
        w('| %s | %s | %s | %s | %s |' % (pos, lk, txt, tpl, mm))
    w('')

    io.open(OUT, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    print('OK: %s — описано %d, лишилося %d' % (OUT, done, len(rows)))
    for tpl, n in by_tpl.most_common(4):
        print('    %-52s %d' % (tpl, n))
    return 0


if __name__ == '__main__':
    sys.exit(main())
