# -*- coding: utf-8 -*-
"""Скільки кроків збірки стоїть за кожною позицією прайсу — і скільки годин продано.

НАВІЩО. Години в прайсі — гіпотези до замірів фази 0, і міняти їх без замірів не
можна. Але заміряти всі 27 позицій підряд дорого, а порядок замірів досі вибирався
навмання. Цей звіт дає **вимірюваний проксі**: скільки кроків і викликів конектора
складається в план для позиції, коли куплено рівень 3.

ЧОГО ЦЕЙ ЗВІТ НЕ РОБИТЬ І НЕ РОБИТИМЕ:

* **не переводить кроки в години.** Крок «створити журнал» і крок «зібрати шаблон
  підпису з координатами» — це різні хвилини, і жодного коефіцієнта тут немає;
* **не пропонує правити прайс.** Розбіжність між кроками й годинами — це привід
  ЗАМІРЯТИ позицію раніше за інші, а не переписати число;
* **не рахує роботу аналітика.** Половина роботи — розмова, рішення й показ; вона
  живе в кроках-послугах, і їх звіт рахує окремо саме тому, що це інша робота.

Як читати. Дві крайності однаково цікаві. Багато кроків при малих годинах — ризик
недооцінки, з цих позицій замір починають. Мало кроків при великих годинах — або
години справді йдуть на розмову й показ (тоді послуг у позиції багато, і це видно
в сусідній колонці), або ціна тримається на чомусь, чого в рецептах немає, і це
теж треба знати до пілоту.

Запуск: python3 tools/report_plan_vs_price.py > docs/кроки-проти-годин.md
"""

import collections
import io
import json
import subprocess
import sys
import tempfile
import os

PRICE = 'data/price.json'
OUT = 'docs/кроки-проти-годин.md'


def план_усіх():
    """План на всі позиції рівня 3 — той самий режим, що перевіряє покриття."""
    tmp = os.path.join(tempfile.mkdtemp(), 'plan.json')
    r = subprocess.run(['python3', 'tools/emit_config_calls.py',
                        'data/client-profile-example.json', '--всі', '--json', tmp],
                       capture_output=True, text=True)
    if r.returncode != 0:
        sys.stderr.write('емітер не склав план:\n%s\n' % (r.stderr or r.stdout))
        sys.exit(1)
    return json.load(io.open(tmp, encoding='utf-8'))


def main():
    price = json.load(io.open(PRICE, encoding='utf-8'))
    план = план_усіх()

    години, назви, групи = {}, {}, {}
    for g in price['групи']:
        for it in g['items']:
            назви[it['n']] = it['id']
            групи[it['n']] = g['g']
            години[it['n']] = it['lv'][2][1]      # рівень 3 — той, що в плані

    кроків = collections.Counter()
    послуг = collections.Counter()
    # ОКРЕМОЇ КОЛОНКИ «ВИКЛИКІВ» ТУТ НЕМАЄ, і це не пропуск. Перша версія звіту її
    # мала — і в кожному рядку вона дорівнювала кількості кроків, бо кроки-послуги
    # емітер віддає окремим переліком, а не серед кроків. Колонка, яка завжди
    # повторює сусідню, читається як факт, а насправді не каже нічого.
    for st in план['кроки']:
        поз = st.get('_позиція')
        if поз:
            кроків[поз] += 1
    # Послуги емітер віддає рядками «Позиція р.N · пункт», а не записами: у плані
    # вони окремим розділом «поза базою». Перша версія звіту брала їх як словники
    # й дала колонку з самих нулів — колонка нулів гірша за відсутню колонку,
    # бо виглядає як факт «послуг немає».
    for рядок in план['послуги']:
        if not isinstance(рядок, str):
            continue
        голова = рядок.split(' р.', 1)[0].strip()
        if голова:
            послуг[голова] += 1

    рядки = []
    for n in назви:
        г = години[n]
        к = кроків.get(n, 0)
        рядки.append({
            'назва': n, 'група': групи[n], 'години': г,
            'кроки': к, 'послуги': послуг.get(n, 0),
            'кроків_на_годину': (к / г) if г else 0.0,
        })
    рядки.sort(key=lambda r: -r['кроків_на_годину'])

    w = print
    w('# Кроки збірки проти проданих годин')
    w('')
    w('**Згенеровано** `tools/report_plan_vs_price.py`. Руками не правити.')
    w('')
    w('> ## ЦЕ НЕ ПІДСТАВА ПРАВИТИ ПРАЙС')
    w('>')
    w('> Години — гіпотези до замірів фази 0, і міняти їх без замірів не можна.')
    w('> Кроки в години не переводяться: «створити журнал» і «зібрати шаблон підпису')
    w('> з координатами» — різні хвилини, коефіцієнта немає. Звіт відповідає рівно')
    w('> на одне питання: **з якої позиції починати замір**.')
    w('')
    w('Рахується план на **рівень 3** кожної позиції — той самий, яким збірка')
    w('перевіряє покриття. «Кроків у базі» — те, що виконує конектор; «кроків-послуг» —')
    w('робота поза базою (розмова, показ, передача), і це ІНША робота, яку кроками')
    w('не міряють. Дві позиції з нулем у першій колонці — «Експрес-діагностика»')
    w('й «Навчання команди» — саме такі: у базі в них не буває нічого.')
    w('')
    усього_к = sum(r['кроки'] for r in рядки)
    усього_г = sum(r['години'] for r in рядки)
    w('| Позиція | Група | Годин р.3 | Кроків у базі | Кроків-послуг | Кроків/год |')
    w('|---|---|---:|---:|---:|---:|')
    for r in рядки:
        w('| %s | %s | %d | %d | %d | %.1f |'
          % (r['назва'], r['група'], r['години'], r['кроки'],
             r['послуги'], r['кроків_на_годину']))
    w('| **Разом** | | **%d** | **%d** | **%d** | %.1f |'
      % (усього_г, усього_к, sum(r['послуги'] for r in рядки),
         (усього_к / усього_г) if усього_г else 0))
    w('')
    w('## З чого починати замір')
    w('')
    верх = рядки[:5]
    низ = [r for r in рядки[-5:] if r['години']]
    w('**Найщільніші за кроками** — тут ризик недооцінки найбільший, і замір із них')
    w('дає найбільше інформації за ту саму годину:')
    w('')
    for r in верх:
        w('- **%s** — %d кроків на %d годин (%.1f на годину), із них послуг %d'
          % (r['назва'], r['кроки'], r['години'], r['кроків_на_годину'], r['послуги']))
    w('')
    w('**Найрідші за кроками** — тут або години справді йдуть на розмову й показ')
    w('(дивіться колонку «послуг»), або ціна тримається на чомусь, чого в рецептах')
    w('немає. Друге треба зʼясувати до пілоту, а не після:')
    w('')
    for r in низ:
        w('- **%s** — %d кроків на %d годин (%.1f на годину), із них послуг %d'
          % (r['назва'], r['кроки'], r['години'], r['кроків_на_годину'], r['послуги']))
    return 0


if __name__ == '__main__':
    sys.exit(main())
