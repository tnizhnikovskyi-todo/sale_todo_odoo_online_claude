"""Вшиває data/price.json і data/qualification.json у artifacts/calculator.html.

Джерело правди для прайсу — data/price.json, для чек-листа кваліфікації
(друга сторінка калькулятора) — data/qualification.json. Калькулятор публікується
як Artifact і не може підвантажувати зовнішні файли, тому дані вшиваються в HTML.

Порядок роботи:
    1. правиш data/price.json або data/qualification.json
    2. python3 tools/build_calculator.py
    3. публікуєш artifacts/calculator.html через Artifact

Скрипт перевіряє структуру перед записом і падає, якщо вона зламана:
3 рівні, зростання годин, ознаки, поля q/bounds/dep, стоп-слова периметра
(«доопрацювання», «доробка», «лише в XML», «умовні блоки», «обчислювані поля», «Studio»
без застереження); у чек-листі — вид блоку, наслідки r, посилання need на
відомі позиції прайсу, пояснення при r=warn/stop.
"""
import collections, io, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'data', 'price.json')
QUAL = os.path.join(ROOT, 'data', 'qualification.json')
FORM = os.path.join(ROOT, 'data', 'client-form.json')
VRFY = os.path.join(ROOT, 'data', 'verify.json')
HTML = os.path.join(ROOT, 'artifacts', 'calculator.html')
RATE = 50  # €/год — та сама ставка, що в самій сторінці
# Частка діагностики, що зараховується у вартість проєкту. Мусить дорівнювати
# `DIAG_CREDIT` у самій сторінці — інакше перевірка стереже не те, що показує
# калькулятор; збіг перевіряється окремо, нижче.
DIAG_CREDIT = 0.5

STOP = ['доопрацюван', 'доробк', 'лише в XML', 'умовні блоки', 'обчислювані поля',
        'studio']  # Studio у прайсі бути не може — рішення 09.09.2026, усі 45
                   # пунктів переведені на штатні шляхи; NEG нижче лишає застереження
NEG = ['немає', 'не робимо', 'поза периметром', 'замість']

def has_stop(text):
    t = text.lower()
    return any(w in t for w in STOP) and not any(n in t for n in NEG)

def check(groups):
    errs, warns = [], []
    ids = set()
    allitems = [it for gr in groups for it in gr.get('items', [])]
    known = set(it.get('id') for it in allitems)
    home = {}
    for it in allitems:
        for mod in it.get('home', []) or []:
            home[mod] = it.get('id')
    for gr in groups:
        if not gr.get('g') or not isinstance(gr.get('items'), list):
            errs.append('група без назви або без items'); continue
        for it in gr['items']:
            iid = it.get('id')
            if not iid: errs.append('позиція без id у групі %s' % gr['g']); continue
            if iid in ids: errs.append('дубль id: %s' % iid)
            ids.add(iid)
            if len(it.get('inc', [])) < 1:
                errs.append('%s: порожній inc' % iid)
            lv = it.get('lv', [])
            if len(lv) != 3:
                errs.append('%s: має бути рівно 3 рівні, а не %d' % (iid, len(lv)))
                continue
            for i, l in enumerate(lv):
                if len(l) != 5:
                    errs.append('%s рівень %d: очікується 5 елементів [назва, години, економія, ознака, додані]' % (iid, i+1))
                    continue
                name, hours, sav, sig, add = l
                if not isinstance(hours, int) or hours <= 0:
                    errs.append('%s рівень %d: години мусять бути додатнім цілим' % (iid, i+1))
                if not (0 <= sav <= 90):
                    errs.append('%s рівень %d: економія поза межами 0..90' % (iid, i+1))
                if not sig:
                    errs.append('%s рівень %d: немає ознаки для вибору' % (iid, i+1))
                elif has_stop(sig):
                    errs.append('%s рівень %d: ознака обіцяє те, що поза периметром: «%s»' % (iid, i+1, sig))
                if i == 0 and add:
                    errs.append('%s: у першого рівня список доданих мусить бути порожнім' % iid)
                for t in add:
                    if has_stop(t):
                        errs.append('%s рівень %d: пункт поза периметром без застереження: «%s»' % (iid, i+1, t))
            for t in it.get('inc', []):
                if has_stop(t):
                    errs.append('%s: базовий пункт поза периметром без застереження: «%s»' % (iid, t))
            hrs = [l[1] for l in lv]
            if hrs != sorted(hrs):
                errs.append('%s: години не зростають за рівнями: %s' % (iid, hrs))
            # нові поля
            if not it.get('q'): warns.append('%s: немає питання сейла (q)' % iid)
            if not it.get('bounds'): warns.append('%s: немає переліку «не входить» (bounds)' % iid)
            # Загальні умови проєкту в «не входить» ОДНІЄЇ позиції — тиха неправда з двох
            # боків: клієнт читає гарантію як обіцянку тільки цієї позиції, а строк стає
            # ще однією копією числа з «Приймання». 10.09.2026 така копія знайшлася в
            # «Базі» («гарантія … 10 робочих днів») і розійшлася б із КП мовчки.
            for t in it.get('bounds', []) or []:
                # «Не входить» друкується в КП окремим рядком-пунктом, тому кожна
                # межа — це речення й починається з великої літери. Дані писалися
                # роками як продовження фрази «не входить: …», і 95 із 107 рядків
                # були з малої: у переліку це виглядало як недописаний текст.
                if t[:1].islower() and t[:1].isalpha():
                    errs.append('%s: рядок «не входить» починається з малої літери — '
                                'у КП це окремий пункт переліку: «%s»' % (iid, t[:60]))
                if re.search(r'гарант\w*[^.;]{0,60}\d+\s*робоч', t):
                    errs.append('%s: строк гарантії названий у «не входить» позиції — '
                                'він загальний для проєкту й живе в розділі «Приймання» '
                                'КП: «%s»' % (iid, t))
            for d in it.get('dep', []) or []:
                ons = d.get('on') if isinstance(d.get('on'), list) else [d.get('on')]
                for t in ons:
                    if t not in known: errs.append('%s: dep на невідому позицію %s' % (iid, t))
                    if t == iid: errs.append('%s: dep на саму себе' % iid)
                if d.get('type') not in ('hard', 'soft'):
                    errs.append('%s: dep.type мусить бути hard або soft' % iid)
                if d.get('from_lv', 1) not in (1, 2, 3) or d.get('min_lv', 1) not in (1, 2, 3):
                    errs.append('%s: dep.from_lv / min_lv мусять бути 1..3' % iid)
                if not d.get('why'): errs.append('%s: dep без пояснення why' % iid)
                # багатоцільова жорстка залежність друкується в КП клієнта («потребує однієї з
                # позицій»), тому службові назви модулів у її пояснення потрапити не можуть
                elif d.get('type') == 'hard' and isinstance(d.get('on'), list) and len(d['on']) > 1:
                    tech = re.findall(r'\b[a-z][a-z_.]{3,}\b', d['why'])
                    if tech:
                        errs.append('%s: пояснення багатоцільової залежності друкується в КП — '
                                    'службові назви %s звідти прибрати' % (iid, tech))
            # тягнеш чужий модуль — мусиш мати dep на його власника (попередження)
            deps_to = set()
            for d in it.get('dep', []) or []:
                for t in (d['on'] if isinstance(d['on'], list) else [d['on']]): deps_to.add(t)
            for lvk, mods in (it.get('apps') or {}).items():
                for mod in mods:
                    owner = home.get(mod)
                    if owner and owner != iid and owner != 'base' and owner not in deps_to:
                        warns.append('%s: тягне %s (власник — %s), але dep на %s немає' % (iid, mod, owner, owner))
    return errs, warns

def check_integrity(groups, vrfy, qual=None):
    """Перевірки цілісності, які не належать жодному окремому файлу.

    Кожна тут не тому, що спрацювала, а тому, що її поломка **тиха**: дані лишаються
    валідними, збірка проходить, а прайс починає обіцяти або показувати неправду.
    Усі вісім відтворені негативними тестами — перевірка, яка нічого не ловить, гірша
    за відсутність перевірки.
    """
    errs, warns = [], []
    items = [it for gr in groups for it in gr['items']]
    pos = (vrfy.get('позиції') or {})

    # 1. Прайс → журнал. check_verify стежить за зворотним напрямом (запис журналу
    # має вести на живий пункт прайсу), а цей бік був відкритий: новий пункт у прайсі
    # ставав обіцянкою, якої немає в жодному звіті — build_kb таку позицію просто
    # пропускає. Попередження, а не помилка: чернетку прайсу писати можна.
    nover = []
    for it in items:
        for k in (1, 2, 3):
            own = it['inc'] if k == 1 else it['lv'][k - 1][4]
            rec = ((pos.get(it['id']) or {}).get(str(k)) or {}).get('пункти') or {}
            for t in own:
                if t not in rec:
                    nover.append('%s р.%d «%s»' % (it['id'], k, t))
    if nover:
        warns.append('пунктів без запису в журналі перевірки: %d — %s%s'
                     % (len(nover), '; '.join(nover[:3]),
                        ' …' if len(nover) > 3 else ''))

    for it in items:
        iid = it['id']

        # 2. Дубль тексту пункту в межах позиції. Журнал перевірки адресує пункт
        # текстом у межах рівня, тому два однакові тексти роблять запис неоднозначним:
        # галочка стане не на той пункт, і ніхто цього не побачить.
        seen = {}
        for k, src in ((1, it['inc']), (2, it['lv'][1][4]), (3, it['lv'][2][4])):
            for t in src:
                if t in seen:
                    errs.append('%s: пункт «%s» повторюється (р.%d і р.%d) — журнал '
                                'адресує пункт текстом, дубль робить запис неоднозначним'
                                % (iid, t, seen[t], k))
                else:
                    seen[t] = k

        # 3. Ціна мусить рости за рівнями. Годинам це вже перевірено, але ціна
        # округляється до 50: 20 і 21 година дають однакову 1000 €, і клієнт бачить
        # два різні рівні за ті самі гроші.
        pr = [int(round(l[1] * RATE / 50.0)) * 50 for l in it['lv']]
        for i in (0, 1):
            if pr[i] >= pr[i + 1]:
                errs.append('%s: після округлення р.%d і р.%d коштують %d і %d — '
                            'два рівні за ті самі гроші; розвести години'
                            % (iid, i + 1, i + 2, pr[i], pr[i + 1]))

        # 4. Ознаки рівнів мусять різнитися: сейл вибирає рівень саме за ознакою,
        # однакові тексти роблять вибір неможливим.
        sigs = [l[3] for l in it['lv']]
        if len(set(sigs)) != len(sigs):
            errs.append('%s: ознаки рівнів повторюються — за ознакою вибирають рівень, '
                        'вона мусить бути різною: %s' % (iid, sigs))

        # 5. home ⊆ apps. `home` каже «цей застосунок наш», і на цьому тримається
        # попередження «тягнеш чужий модуль без dep». Модуль, названий своїм, але
        # відсутній у власних apps, робить власника фіктивним.
        apps = set(m for mods in (it.get('apps') or {}).values() for m in mods)
        for m in it.get('home') or []:
            if m not in apps:
                errs.append('%s: застосунок «%s» названий своїм (home), але його немає '
                            'в apps цієї позиції — власник фіктивний' % (iid, m))

    # 6. Цикл у жорстких залежностях. Калькулятор додає жорсткі залежності сам, а
    # процедура збірки шукає порядок топологічним сортуванням — цикл ламає обидва.
    hard = {}
    for it in items:
        tgt = set()
        for d in it.get('dep') or []:
            if d.get('type') == 'hard':
                for t in (d['on'] if isinstance(d['on'], list) else [d['on']]):
                    tgt.add(t)
        hard[it['id']] = tgt
    done, cycles = set(), []
    def walk_hard(n, stack):
        if n in stack:
            cycles.append(' → '.join(stack[stack.index(n):] + [n]))
            return
        if n in done:
            return
        done.add(n)
        for m in hard.get(n, ()):
            walk_hard(m, stack + [n])
    for it in items:
        walk_hard(it['id'], [])
    for c in cycles:
        errs.append('цикл у жорстких залежностях: %s — калькулятор додає їх сам, '
                    'а процедура збірки шукає порядок сортуванням; цикл ламає обидва' % c)

    # 7. Хибне підтвердження: «знайшли» посилається на ІНШУ перевірку замість власної
    # знахідки, а «є» при цьому true. Це найтихіша поломка звірки з усіх: питання
    # виглядає закритим, у звіті стоїть «є в базі», а в базі нічого немає.
    #
    # Знайдено не теорією: 10.09.2026 таких записів було 11, і чотири з них
    # («поля наряду», «поля стану обʼєкта», «поля категорій і лімітів», «власні поля
    # в картці співробітника») виявились неправдою — переліки властивостей у базі
    # були порожні. Решта сім мали справжній артефакт, просто описаний ліниво.
    #
    # Тому правило вимагає не «не згадуй попередню перевірку», а «назви, що бачив
    # САМЕ ТУТ»: посилання дозволене поряд із власним доказом — id запису, назвою
    # в лапках або технічною адресою з крапкою (модель.поле).
    ПОСИЛАННЯ = re.compile(
        r'перевірен[оаіи][^.]{0,30}\b(раніше|вище)\b|(?<!\w)див\.|те\s+саме,?\s+що|'
        r'той\s+самий\s+запис|як\s+у\s+пункт|аналогічно', re.I | re.U)
    ДОКАЗ = re.compile(r'\bid\s*\d+|«[^»]+»|[a-z_]+\.[a-z_]+', re.I | re.U)
    for iid, lvs in pos.items():
        for lv, blk in (lvs or {}).items():
            for txt, rec in ((blk or {}).get('пункти') or {}).items():
                z = rec.get('звірка') or {}
                if not z.get('є'):
                    continue
                знайшли = z.get('знайшли') or ''
                if ПОСИЛАННЯ.search(знайшли) and not ДОКАЗ.search(знайшли):
                    errs.append('%s р.%s «%s»: звірка каже «є в базі», але «знайшли» лише '
                                'посилається на іншу перевірку й не називає жодного доказу '
                                '(id запису, назви в лапках, моделі з полем). Саме так '
                                'чотири порожні переліки властивостей простояли підтвердженими'
                                % (iid, lv, txt[:50]))

    # 8. Число в пояснені проти прайсу. Пояснення чек-листа називає «обовʼязковий
    # мінімум» конкретною сумою — а це ПОХІДНА від прайсу: «База» обовʼязкова, а
    # «Рахунки та оплати» тягне будь-хто, хто виставляє рахунки. Поправте години
    # Бази — і сейл почне казати клієнтові неправду, бо число живе в тексті, а не
    # в даних. Той самий клас, що застаріла концепція: цифра в прозі відв’язується
    # від джерела мовчки.
    if qual:
        база = next((it for it in items if it.get('id') == 'base'), None)
        рахунки = next((it for it in items if it.get('id') == 'inv'), None)
        if база and рахунки:
            мінімум = int(round((база['lv'][0][1] + рахунки['lv'][0][1]) * RATE / 50.0) * 50)
            ЄВРО = re.compile(r'€\s*([\d  ]+)')
            # qual тут — ПЕРЕЛІК блоків, а не весь файл: спіймано на першому ж запуску
            for b_ in qual:
                for q_ in b_.get('питання') or []:
                    for a_ in q_.get('a') or []:
                        нота = a_.get('note') or ''
                        if 'мінімум' not in нота.lower():
                            continue
                        for знач in ЄВРО.findall(нота):
                            ч = int(знач.replace(' ', '').replace(' ', '').replace(' ', ''))
                            if ч != мінімум:
                                errs.append('чек-лист, питання «%s»: пояснення називає '
                                            'обовʼязковий мінімум €%d, а за прайсом це '
                                            '€%d («База» р.1 + «Рахунки та оплати» р.1). '
                                            'Число в прозі відвʼязалося від джерела'
                                            % (q_.get('id'), ч, мінімум))

    # 9. Залік діагностики проти найдешевшого можливого проєкту. Діагностика
    # оплачується окремо, і частина її суми зараховується у вартість проєкту
    # (рішення 10.09.2026 — половина). Поки залік був повним, існував випадок,
    # у якому він зʼїдав увесь проєкт: діагностика рівня 3 (€1 000) при наборі
    # «тільки База» рівня 1 (€800) перекривала його цілком, і клієнт не доплачував
    # нічого. Половина знімає це арифметично, але **не назавжди**: досить підняти
    # години діагностики або опустити години Бази, і випадок повернеться — мовчки,
    # бо обидва числа лежать у різних позиціях прайсу.
    #
    # Тому перевіряється саме інваріант, а не число: максимальний залік мусить
    # бути МЕНШИМ за найдешевший можливий проєкт. Найдешевший — це «тільки База»
    # рівня 1, бо База обовʼязкова, а «Рахунки та оплати» вона не тягне.
    діаг = next((it for it in items if it.get('id') == 'diag'), None)
    база = next((it for it in items if it.get('id') == 'base'), None)
    if діаг and база:
        макс_залік = int(round(діаг['lv'][2][1] * RATE * DIAG_CREDIT / 50.0) * 50)
        мін_проєкт = int(round(база['lv'][0][1] * RATE / 50.0) * 50)
        if макс_залік >= мін_проєкт:
            errs.append('залік діагностики (%d %% від рівня 3 = €%d) не менший за '
                        'найдешевший можливий проєкт «тільки База» рівня 1 (€%d): '
                        'існує набір, у якому клієнт не доплачує нічого або доплачує '
                        'вʼїмʼя. Це не помилка даних, а комерційна діра — вирішувати '
                        'треба часткою заліку або цінами, не перевіркою'
                        % (int(DIAG_CREDIT * 100), макс_залік, мін_проєкт))

    return errs, warns

def check_qual(blocks, known):
    """Перевіряє чек-лист кваліфікації. known — id позицій прайсу для посилань need."""
    errs, warns = [], []
    ids = set()
    for b in blocks:
        bid = b.get('id')
        if not bid: errs.append('блок чек-листа без id'); continue
        if bid in ids: errs.append('дубль id блоку чек-листа: %s' % bid)
        ids.add(bid)
        if not b.get('назва'): errs.append('%s: блок без назви' % bid)
        if b.get('вид') not in ('питання', 'чеклист'):
            errs.append('%s: вид блоку мусить бути «питання» або «чеклист»' % bid)
            continue
        if not b.get('під'): warns.append('%s: блок без підзаголовка (під)' % bid)
        if b['вид'] == 'чеклист':
            if not b.get('пункти'): errs.append('%s: чеклист без пунктів' % bid)
            for p in b.get('пункти', []):
                if not p.get('id') or not p.get('t'):
                    errs.append('%s: пункт чек-листа без id або тексту' % bid)
                if not p.get('note'):
                    warns.append('%s/%s: пункт без пояснення, чим загрожує незакритий' % (bid, p.get('id')))
            continue
        if not b.get('питання'): errs.append('%s: блок питань без питань' % bid)
        for q in b.get('питання', []):
            qid = '%s/%s' % (bid, q.get('id'))
            if not q.get('id'): errs.append('%s: питання без id' % bid)
            if not q.get('q'): errs.append('%s: питання без формулювання' % qid)
            elif has_stop(q['q']): errs.append('%s: питання обіцяє те, що поза периметром' % qid)
            ans = q.get('a') or []
            if len(ans) < 2: errs.append('%s: у питання мусить бути щонайменше дві відповіді' % qid)
            for a in ans:
                if not a.get('t'): errs.append('%s: відповідь без формулювання' % qid)
                if a.get('r') not in ('ok', 'warn', 'stop'):
                    errs.append('%s: наслідок відповіді (r) мусить бути ok, warn або stop' % qid)
                if a.get('r') in ('warn', 'stop') and not a.get('note'):
                    errs.append('%s: відповідь «%s» без пояснення note' % (qid, a.get('r')))
                if a.get('note') and has_stop(a['note']):
                    errs.append('%s: note обіцяє те, що поза периметром: «%s»' % (qid, a['note']))
                for t in a.get('need', []) or []:
                    # need — id позиції або {on, lv}: рівень, не нижче якого її треба поставити
                    on, lv = (t.get('on'), t.get('lv')) if isinstance(t, dict) else (t, None)
                    if on not in known: errs.append('%s: need на невідому позицію %s' % (qid, on))
                    if lv is not None and lv not in (1, 2, 3):
                        errs.append('%s: need.lv мусить бути 1..3, а не %r' % (qid, lv))
            if not any(a.get('r') == 'ok' for a in ans):
                warns.append('%s: немає відповіді без наслідків — питання не розділяє лідів' % qid)
    return errs, warns

REF = re.compile(r'«([^»]+)»\s*рівня\s*(\d)')

def check_refs(text, where, pos_names, errs, warns):
    """Посилання «Назва» рівня N у «що слухати» мусить вести на живу позицію прайсу.
    Позиції перейменовують — без цієї перевірки чек-лист тихо починає називати те,
    чого в прайсі вже немає."""
    for m in REF.finditer(text or ''):
        nm, lv = m.group(1), int(m.group(2))
        if not 1 <= lv <= 3:
            errs.append('%s: посилання на рівень %d — рівнів три' % (where, lv))
        if nm in pos_names:
            continue
        hit = [n for n in pos_names if n.startswith(nm)]
        if len(hit) == 1:
            warns.append('%s: «%s» — скорочена назва позиції «%s»' % (where, nm, hit[0]))
        elif hit:
            errs.append('%s: «%s» підходить кільком позиціям: %s' % (where, nm, ', '.join(hit)))
        else:
            errs.append('%s: посилання на позицію «%s», якої в прайсі немає' % (where, nm))

def check_probes(probes, group_names, pos_names=()):
    """Перевіряє питання на глибину: ключ = назва групи прайсу, 5-7 питань, є «що слухати»."""
    errs, warns = [], []
    for grp, items in (probes or {}).items():
        if grp not in group_names:
            errs.append('глибина: невідома група «%s» (ключ мусить збігатися з назвою групи в прайсі)' % grp)
            continue
        if not isinstance(items, list) or not items:
            errs.append('глибина/%s: порожній список питань' % grp); continue
        if not (8 <= len(items) <= 14):
            warns.append('глибина/%s: %d питань, а треба 8-14' % (grp, len(items)))
        ids = set()
        for it in items:
            pid = '%s/%s' % (grp, it.get('id'))
            if not it.get('id'): errs.append('глибина/%s: питання без id' % grp)
            elif it['id'] in ids: errs.append('глибина: дубль id %s' % pid)
            else: ids.add(it['id'])
            if not it.get('q'): errs.append('глибина/%s: питання без формулювання' % pid)
            elif has_stop(it['q']): errs.append('глибина/%s: питання обіцяє те, що поза периметром' % pid)
            if not it.get('hear'): errs.append('глибина/%s: немає «що слухати» (hear)' % pid)
            elif has_stop(it['hear']): errs.append('глибина/%s: «що слухати» обіцяє те, що поза периметром' % pid)
            else: check_refs(it['hear'], 'глибина/%s' % pid, pos_names, errs, warns)
    missing = [g for g in group_names if g not in (probes or {})]
    for g in missing: warns.append('глибина: для групи «%s» питань немає' % g)
    return errs, warns

def check_form(form, known):
    """Перевіряє анкету клієнта: типи полів, унікальність id, посилання на позиції прайсу.

    Аудиторія анкети — клієнт, тому окремо ловимо внутрішню лексику: рівнів, цін,
    «стопів» і слова «контур» у питаннях до клієнта бути не має.
    """
    errs, warns = [], []
    INNER = ['рівень', 'рівня', 'стоп-', 'наш контур', 'прайс', 'маржа', '€', 'дискваліф']
    TYPES = ('текст', 'абзац', 'вибір')
    seen = set()
    if not form.get('вступ'): warns.append('анкета: немає вступу для клієнта')

    def fields(where, items):
        for f in items:
            fid = '%s/%s' % (where, f.get('id'))
            if not f.get('id'): errs.append('%s: поле без id' % where)
            elif fid in seen: errs.append('анкета: дубль поля %s' % fid)
            else: seen.add(fid)
            if not f.get('q'): errs.append('%s: поле без питання' % fid)
            elif has_stop(f['q']): errs.append('%s: питання обіцяє те, що поза периметром' % fid)
            else:
                low = f['q'].lower()
                for w in INNER:
                    if w in low: errs.append('%s: у питанні до клієнта внутрішня лексика «%s»' % (fid, w))
            if f.get('тип') not in TYPES:
                errs.append('%s: тип мусить бути %s' % (fid, ' / '.join(TYPES)))
            if f.get('тип') == 'вибір' and len(f.get('опції') or []) < 2:
                errs.append('%s: у полі-виборі мусить бути щонайменше дві опції' % fid)
            if f.get('тип') != 'вибір' and f.get('опції'):
                errs.append('%s: опції має тільки поле-вибір' % fid)

    secs = (form.get('розділи') or []) + (form.get('розділи2') or [])
    if not secs: errs.append('анкета: немає постійних розділів')
    for sec in secs:
        if not sec.get('id') or not sec.get('назва'):
            errs.append('анкета: розділ без id або назви'); continue
        if not sec.get('поля'): errs.append('анкета/%s: розділ без полів' % sec['id'])
        for t in sec.get('позиції') or []:
            if t not in known: errs.append('анкета/%s: посилання на невідому позицію прайсу %s' % (sec['id'], t))
        fields(sec['id'], sec.get('поля') or [])
    procs = form.get('процеси') or []
    if not procs: errs.append('анкета: немає блоків процесів')
    for pr in procs:
        pid = pr.get('id')
        if not pid or not pr.get('назва'):
            errs.append('анкета: процес без id або назви'); continue
        if not pr.get('питання'): errs.append('анкета/%s: процес без питань' % pid)
        elif not (4 <= len(pr['питання']) <= 8):
            warns.append('анкета/%s: %d питань, а треба 4-8: клієнт відповідає сам, довгий блок він покине'
                         % (pid, len(pr['питання'])))
        for t in pr.get('позиції') or []:
            if t not in known: errs.append('анкета/%s: посилання на невідому позицію прайсу %s' % (pid, t))
        if not pr.get('позиції'): warns.append('анкета/%s: процес не зіставлений із позиціями прайсу' % pid)
        fields(pid, pr.get('питання') or [])
    return errs, warns

VSTAT = ('ok', 'fail', 'move', 'skip')

def composition(item, lv):
    """Накопичений склад робіт рівня lv (0-based): inc + додані на 1-му і 2-му."""
    out = list(item['inc'])
    for k in range(1, lv + 1):
        out += list(item['lv'][k][4])
    return out

def check_verify(vrfy, groups):
    """Журнал перевірки на базі: id позицій, номери рівнів, тексти пунктів — живі."""
    errs, warns = [], []
    byid = dict((it['id'], it) for gr in groups for it in gr['items'])
    for pid, lvs in (vrfy.get('позиції') or {}).items():
        if pid not in byid:
            errs.append('verify: позиції «%s» у прайсі немає' % pid)
            continue
        item = byid[pid]
        for lk, rec in lvs.items():
            if lk not in ('1', '2', '3'):
                errs.append('verify %s: рівень «%s» — має бути 1, 2 або 3' % (pid, lk))
                continue
            comp = composition(item, int(lk) - 1)
            if not rec.get('дата'):
                warns.append('verify %s р.%s: немає дати перевірки' % (pid, lk))
            for txt, st in (rec.get('пункти') or {}).items():
                own = item['inc'] if lk == '1' else item['lv'][int(lk) - 1][4]
                if txt not in comp:
                    errs.append('verify %s р.%s: пункту «%s» у складі робіт цього рівня '
                                'немає — прайс перейменували, звірити' % (pid, lk, txt))
                elif txt not in own:
                    warns.append('verify %s р.%s: пункт «%s» додається на іншому рівні — '
                                 'запис тримати там, де пункт з’явився' % (pid, lk, txt))
                c = st.get('с')
                if c not in VSTAT:
                    errs.append('verify %s р.%s «%s»: статус «%s» — можна лише %s'
                                % (pid, lk, txt, c, '/'.join(VSTAT)))
                if c in ('fail', 'move', 'skip') and not st.get('нота'):
                    errs.append('verify %s р.%s «%s»: статус %s без пояснення'
                                % (pid, lk, txt, c))
                z = st.get('звірка')
                if z is not None:
                    for k in ('дата', 'дивились', 'знайшли'):
                        if not z.get(k):
                            errs.append('verify %s р.%s «%s»: у звірці немає «%s»'
                                        % (pid, lk, txt, k))
                    if not isinstance(z.get('є'), bool):
                        errs.append('verify %s р.%s «%s»: у звірці «є» має бути так або ні'
                                    % (pid, lk, txt))
    return errs, warns

def межі_блоку(html, name):
    """Де в HTML лежить літерал `var NAME = …;` — щоб відрізнити дані від коду."""
    a = html.index('var ' + name + ' = ')
    body = a + len('var ' + name + ' = ')
    depth, i, n = 0, body, len(html)
    while i < n:
        c = html[i]
        if c in '[{':
            depth += 1
        elif c in ']}':
            depth -= 1
            if depth == 0:
                i += 1
                break
        i += 1
    return a, html.index(';', i) + 1


def check_diag_credit_const(html):
    """Частка заliku в коді сторінки мусить дорівнювати тій, якою рахує перевірка.

    Дві копії одного числа — рівно той клас, від якого цей проєкт страждав усю ніч.
    Тут копій дві неминуче (Python перевіряє, JS показує), тому вони звіряються.
    """
    m = re.search(r'var DIAG_CREDIT = ([\d.]+);', html)
    if not m:
        return ['у коді сторінки немає `var DIAG_CREDIT` — залік діагностики '
                'перестав бути одним числом']
    якщо = float(m.group(1))
    if abs(якщо - DIAG_CREDIT) > 1e-9:
        return ['частка заліку діагностики: у сторінці %s, а перевірка рахує %s'
                % (якщо, DIAG_CREDIT)]
    return []


def рядки_блоку(html, name):
    """Рядкові літерали з `var NAME = [...]` — фіксований текст КП як список рядків."""
    a, b = межі_блоку(html, name)
    return [m.group(1) for m in re.finditer(r"'((?:[^'\\]|\\.)*)'", html[a:b])]


def check_kp_refs(html):
    """Посилання «пункт N розділу «Приймання»» мусить вести на живий пункт.

    Розділ «Оплата» називає момент другого платежу не словами, а НОМЕРОМ пункту
    приймання — і це рівно та поломка, від якої весь цей репозиторій має сторожів:
    достатньо вставити пункт у середину «Приймання», і КП починає посилати клієнта
    не туди. Тихо: текст валідний, збірка проходить, а платіж прив'язаний до
    іншого правила.

    Перевіряється дві речі: пункт із таким номером існує, і він справді про
    ЗАКРИТТЯ проєкту (слово «закрит»). Друга половина навмисно змістова: якщо
    правило закриття переписали іншими словами, посилання мусить перечитати
    людина, а не збірка вирішити за неї.
    """
    рядки = рядки_блоку(html, 'KP_TERMS')
    try:
        поч = рядки.index('ПРИЙМАННЯ')
    except ValueError:
        return ['у фіксованому тексті КП немає розділу «ПРИЙМАННЯ»']
    кінець = len(рядки)
    for i in range(поч + 1, len(рядки)):
        if рядки[i] == '':
            кінець = i
            break
    пункти = {}
    поточний = None
    for рядок in рядки[поч + 1:кінець]:
        m = re.match(r'(\d+)\.\s+(.*)', рядок)
        if m:
            поточний = m.group(1)
            пункти[поточний] = m.group(2)
        elif поточний:
            пункти[поточний] += ' ' + рядок.strip()
    errs = []
    for m in re.finditer(r'пункт (\d+) розділу «Приймання»', html):
        n = m.group(1)
        if n not in пункти:
            errs.append('КП посилається на «пункт %s розділу «Приймання»», а таких '
                        'пунктів там %s — посилання веде в порожнє місце'
                        % (n, ', '.join(sorted(пункти)) or 'немає'))
        elif 'закрит' not in пункти[n].lower():
            errs.append('КП прив\'язує другий платіж до пункту %s приймання, але цей '
                        'пункт уже не про закриття проєкту: «%s…»'
                        % (n, пункти[n][:80]))
    return errs


def check_kp_window(html):
    """Гарантійне вікно в КП — сума двох інших чисел того ж розділу.

    «5 робочих днів на зауваження» + «10 робочих днів на дефекти» = «15 робочих
    днів від демонстрації». Число 15 не існує саме по собі: воно похідне, лежить
    у прозі й розійтися може з обох боків. Той самий клас, що восьма перевірка
    цілісності (сума «обов'язкового мінімуму» в чек-листі).
    """
    текст = ' '.join(рядки_блоку(html, 'KP_TERMS'))
    зауваження = re.findall(r'(\d+) робочих днів на зауваження', текст)
    молчання = re.findall(r'зауважень за (\d+) робочих днів', текст)
    дефекти = re.findall(r'(\d+) робочих днів після приймання позиції', текст)
    вікна = re.findall(r'(\d+) робочих днів від', текст)
    errs = []
    if not (зауваження and молчання and дефекти and вікна):
        return ['у «Прийманні» КП зникло одне з чисел строку — вікно на зауваження, '
                'на дефекти або сумарне; перевірити руками']
    if len(set(зауваження + молчання)) != 1:
        errs.append('строк на зауваження в КП названий по-різному: %s і %s робочих днів'
                    % (', '.join(зауваження), ', '.join(молчання)))
    сума = int(зауваження[0]) + int(дефекти[0])
    for w in set(вікна):
        if int(w) != сума:
            errs.append('КП обіцяє «%s робочих днів від демонстрації», а з власних '
                        'чисел виходить %d (%s на зауваження + %s на дефекти)'
                        % (w, сума, зауваження[0], дефекти[0]))
    return errs


def check_kp_half(html):
    """Слово «половина» у клієнтському тексті законне лише поки залік — половина.

    Частку заліку тримає одне число (DIAG_CREDIT), але КЛІЄНТ читає слово, і слів
    цих у сторінці три: підказка сейлу, рядок КП і розділ «Оплата». Зміна числа
    на 0,3 залишила б три обіцянки «половини» — валідні, зібрані й неправдиві.
    """
    a, b = межі_блоку(html, 'VERIFY')
    код = html[:a] + html[b:]          # нотатки журналу «половину пункту» — не про залік
    скільки = len(re.findall('половин', код, re.I))
    половина = abs(DIAG_CREDIT - 0.5) < 1e-9
    if половина and not скільки:
        return ['залік діагностики — половина, але слова «половина» в клієнтському '
                'тексті немає: клієнт бачить число без правила']
    if not половина and скільки:
        return ['залік діагностики тепер %s, а клієнтський текст %d раз(и) обіцяє '
                '«половину»' % (DIAG_CREDIT, скільки)]
    return []


def фіксований_текст(html):
    """Текст КП, який не залежить від набору: блок `KP_TERMS` і функція `payment`."""
    рядки = рядки_блоку(html, 'KP_TERMS')
    a = html.index('function payment(){')
    b = html.index('\n  }', a)
    return '\n'.join(рядки) + '\n' + html[a:b]


