def check_hidden_pages(html):
    """Сторінки, сховані рішенням, мусять бути і сховані, і НЕ видалені.

    «Повний перелік» — внутрішній довідник аналітика: 549 рядків прайсу з
    галочками. У публікації для сейла входу до нього немає (рішення 10.09.2026),
    але сама сторінка лишається — її вмикають одним рядком.

    Тому перевіряються дві протилежні речі, і кожна ловить свою помилку:
    id є у списку `СХОВАНІ` (інакше сторінка тихо повернулась користувачеві) і
    розмітка на місці (інакше «сховати» перетворилось на «видалити», і повернути
    вже нічого).
    """
    m = re.search(r'var СХОВАНІ = \[([^\]]*)\];', html)
    if not m:
        return ['у коді сторінки немає `var СХОВАНІ` — перелік схованих сторінок '
                'перестав бути одним місцем']
    у_списку = set(re.findall(r"'([^']+)'", m.group(1)))
    errs = []
    for pid, назва in СХОВАНІ_СТОРІНКИ.items():
        if pid not in у_списку:
            errs.append('сторінка «%s» (%s) знову видима — рішенням вона схована'
                        % (назва, pid))
        for id_ in ('tab-' + pid, 'page-' + pid):
            if ('id="%s"' % id_) not in html:
                errs.append('сторінка «%s»: розмітки `%s` немає — її не сховали, '
                            'а видалили' % (назва, id_))
    return errs


def check_kp_wrap(html):
    """У фіксованому тексті КП не буває ручних переносів рядка.

    Текст писався з переносами й відступом продовження на два пробіли — рівно так,
    як виглядає добре в монospace-полі шириною 110 символів. Але клієнт бачить його
    пропорційним шрифтом і будь-якої ширини: переноси падають у середину речень, а
    відступи продовження дають драбинку з обірваних піврядків. 10.09.2026 власник
    показав це скриншотами тричі підряд.

    Тому кожен рядок блоку — цілий логічний пункт: або порожній, або заголовок
    розділу, або «- пункт», або «N. пункт». Рядок, що починається з пробілу, — це
    повернений ручний перенос.
    """
    errs = []
    for рядок in рядки_блоку(html, 'KP_TERMS'):
        if рядок.startswith(' '):
            errs.append('фіксований текст КП: рядок починається з відступу — це ручний '
                        'перенос, а клієнт бачить текст пропорційним шрифтом і будь-якої '
                        'ширини: «%s»' % рядок.strip()[:60])
    return errs[:3]


def check_kp_words(html):
    """Дві теми, знятих рішенням 10.09.2026, у фіксованому тексті КП.

    **Нічого не підписуємо — тільки погодження.** Слово «підписати» в умовах
    обіцяє процедуру, якої в контурі немає, і клієнт починає її чекати.
    **ПДВ за законодавством України** прибрано теж: у КП сказано лише «ціни в
    євро, без ПДВ».

    Правило дивиться ТІЛЬКИ на фіксовану частину, і це не перестраховка:
    «підписання у браузері за посиланням» — це проданий пункт прайсу (Odoo Sign),
    тобто на наборі з ним правило по всьому КП кричало б на правильних даних.
    Друга пастка тієї самої мови: **«підписка» має той самий корінь**, що «підпис»,
    — тому «к» і «ц» після кореня виключені (підписку, підписці), інакше правило
    падає на власному розділі «Оплата». Обидві пастки спіймані першим прогоном.
    """
    текст = фіксований_текст(html)
    errs = []
    for m in re.finditer('підпис(?![кц])', текст):
        errs.append('умови КП обіцяють підписання, а рішення — тільки погодження: '
                    '«…%s…»' % текст[max(0, m.start() - 50):m.end() + 30].replace('\n', ' '))
    if 'за законодавством' in текст:
        errs.append('умови КП посилаються на законодавство про ПДВ — формулювання '
                    'знято, лишається «ціни в євро, без ПДВ»')
    return errs[:3]


def check_client_text(html):
    """Стоп-слова знятих тем у КЛІЄНТСЬКОМУ тексті калькулятора.

    Той самий сторож, що для концепції (`tools/check_concept.py`), і потрібен він
    тут навіть більше: текст КП іде **клієнтові**. Прайс від стоп-слів захищений
    давно, а статична проза — «що не входить», умови, приймання, опис рівнів —
    не перевірялася ніяк, хоча живе в тому самому файлі й правиться руками.

    Перевіряється КОД сторінки, а не дані: у нотатках журналу (`VERIFY`) Studio
    згадується законно — це історія перевірки, і на четвертій сторінці її читає
    аналітик, а не клієнт. 10.09.2026 таких згадок 16, і жодна не помилка.

    Взято лише те, що знято рішеннями повністю: ПРРО, КЕП, фіскалізація,
    «Рахунки та податки». Слова «облік» і «податки» законні — межа саме ними й
    формулюється («облік у базі не ведеться»).
    """
    errs = []
    # КОД = усе, що ПОЗА блоками даних. Перша версія брала «усе до першого блоку»
    # — і мовчки не дивилася на текст КП, бо блоки даних стоять у файлі РАНІШЕ за
    # прозу. Отрута з ПРРО не спрацювала й показала це: перевірка виглядала
    # пройденою, а дивилася на розмітку й стилі.
    діапазони = []
    for ім in ('GROUPS', 'QUAL', 'PROBES', 'FORM', 'VERIFY'):
        try:
            діапазони.append(межі_блоку(html, ім))
        except ValueError:
            continue
    діапазони.sort()
    частини, курсор = [], 0
    for a_, b_ in діапазони:
        частини.append(html[курсор:a_])
        курсор = b_
    частини.append(html[курсор:])
    код = '\n'.join(частини)
    for w in ('ПРРО', 'КЕП', 'фіскаліз', 'Рахунки та податки'):
        if w.lower() in код.lower():
            errs.append('клієнтський текст калькулятора містить «%s» — тему знято '
                        'з контуру, у КП її не буває' % w)
    for m in re.finditer('Studio', код):
        вікно = код[max(0, m.start() - 140):m.end() + 140]
        if not any(x in вікно for x in ('не відкриваємо', 'без Studio', 'ні в Studio')):
            errs.append('клієнтський текст: «Studio» без заперечення — «…%s…»'
                        % re.sub(r'<[^>]+>', '', вікно)[60:170].strip())
    return errs


def inject(html, name, value):
    """Замінює тіло `var NAME = …;` у HTML на value, зберігаючи відступ рядка."""
    a = html.index('var ' + name + ' = ')
    body = a + len('var ' + name + ' = ')
    depth, i, n = 0, body, len(html)
    while i < n:                      # шукаємо кінець літерала за балансом дужок
        c = html[i]
        if c in '[{': depth += 1
        elif c in ']}':
            depth -= 1
            if depth == 0: i += 1; break
        i += 1
    end = html.index(';', i)
    line = html.rindex('\n', 0, a) + 1
    indent = html[line:a]
    block = indent + 'var ' + name + ' = ' + json.dumps(
        value, ensure_ascii=False, indent=2).replace('\n', '\n' + indent)
    return html[:line] + block + html[end:]

