"""Рішення власника по прайсу від 03.09.2026 (закриття розділу 11 docs/аналіз-прайсу.md).

1. Нова позиція «Рахунки та податки» (inv) — власник модулів account / l10n_ua;
   усі позиції з рахунками отримують dep на неї замість розмитого dep на «Управлінський облік».
2. База р.1 — український фундамент (мова, часовий пояс, валюта, нумерація, 2FA) і оглядова сесія.
3. Набори (kit) переносяться зі Складу р.2 у Виробництво р.1; партії й серійні номери — зі Складу р.3 у р.2.
4. Картки виконавців — у базові пункти Проєктів, Витрат, Планування, Виїзних робіт.
5. Ціни в КП — без ПДВ (правка в calculator.html окремо).

Години й економія не змінюються: це гіпотези до замірів фази 0.
Спирається на факти стенда з docs/звіт-перевірки-стенда-2026-09-03.md.

Запуск з кореня репозиторію: python3 docs/аналіз-прайсу/скрипти/apply_decisions_2026-09-03.py
"""
import io, json, os, sys

PRICE = os.path.join(os.getcwd(), 'data', 'price.json')
p = json.load(io.open(PRICE, encoding='utf-8'))
groups = p['групи']
items = {it['id']: it for g in groups for it in g['items']}

def lst(iid, where):
    return items[iid]['inc'] if where == 'inc' else items[iid]['lv'][where][4]

def rep(iid, where, old, new):
    l = lst(iid, where)
    hits = [i for i, s in enumerate(l) if s == old]
    assert len(hits) == 1, 'не знайдено або дубль: %s/%s «%s»' % (iid, where, old)
    l[hits[0]] = new

def drop(iid, where, old):
    l = lst(iid, where)
    hits = [i for i, s in enumerate(l) if s == old]
    assert len(hits) == 1, 'не знайдено або дубль: %s/%s «%s»' % (iid, where, old)
    return l.pop(hits[0])

def dep_del(iid, on, from_lv=None):
    d = items[iid]['dep']
    keep = [x for x in d if not (x['on'] == on and (from_lv is None or x.get('from_lv') == from_lv))]
    assert len(keep) < len(d), '%s: немає dep на %s (from_lv=%s)' % (iid, on, from_lv)
    items[iid]['dep'] = keep

def dep_add(iid, on, type_, from_lv, why, min_lv=None):
    rec = {'on': on, 'type': type_, 'from_lv': from_lv, 'why': why}
    if min_lv: rec['min_lv'] = min_lv
    items[iid]['dep'].append(rec)

# ---------- 1. Нова позиція «Рахунки та податки» ----------
INV = {
    "id": "inv",
    "n": "Рахунки та податки",
    "d": "журнали, ПДВ, умови оплати, банк",
    "inc": [
        "журнали продажів, купівель, банку й каси",
        "план рахунків ПСБО і ставки ПДВ 20/14/7/0 (штатний l10n_ua)",
        "статус платника ПДВ і податки в товарах і контрагентах",
        "умови оплати й банківські реквізити в документах",
        "перевірка стандартного бланка рахунку",
    ],
    "lv": [
        ["Базовий", 6, 35, "один банк, одна юрособа, усі операції з ПДВ або всі без нього", []],
        ["Стандарт", 10, 35, "кілька банків чи кас, є неплатники або експорт, потрібен імпорт виписки", [
            "кілька банківських рахунків і кас",
            "фіскальні позиції для неплатника ПДВ і експорту (у l10n_ua їх немає — налаштовуються під клієнта)",
            "імпорт банківської виписки CAMT.053 / CSV / OFX із мапінгом колонок",
            "поля реквізитів у документі (Studio)",
        ]],
        ["Розширений", 16, 30, "кілька юросіб або валютні рахунки", [
            "журнали, податки й нумерація для кожної юрособи",
            "валютні рахунки; курси НБУ — вручну або імпортом",
            "звірка виписки з документами й контроль незакритих",
        ]],
    ],
    "q": "Хто виписує рахунки клієнтам і чи ви платник ПДВ?",
    "bounds": [
        "податкові накладні, РК, ЄРПН і ПДВ-звітність — у BAS у вашого бухгалтера",
        "автоматична синхронізація з українськими банками не гарантується — виписка імпортується файлом",
        "курси НБУ автоматично не завантажуються",
        "каса Odoo — управлінський журнал, не касова книга",
        "первинні документи українського зразка (рахунок, видаткова, акт) — позиція «Друковані форми»",
    ],
    "apps": {"1": ["account", "l10n_ua"], "2": [], "3": []},
    "home": ["account", "l10n_ua"],
    "dep": [],
}
osnova = [g for g in groups if g['g'] == 'Основа'][0]
assert 'inv' not in items, 'позиція inv уже існує'
osnova['items'].insert(1, INV)
items['inv'] = INV

# усі позиції з account/l10n_ua отримують dep на inv замість розмитого dep на acc
WHY_INV = 'рахунок клієнту чи постачальнику виписується в налаштованих журналах із правильною ставкою ПДВ — це позиція «Рахунки та податки»'
for iid, from_lv in [('sal', 1), ('pur', 1), ('pos', 1), ('shop', 1), ('sub', 1), ('rnt', 1), ('exp', 1)]:
    dep_del(iid, 'acc', 1)
    dep_add(iid, 'inv', 'hard', from_lv, WHY_INV)
dep_del('prj', 'acc', 2)
dep_add('prj', 'inv', 'hard', 2, 'рахунок за витраченим часом виставляється в журналі продажів із ставкою ПДВ')
dep_add('fsm', 'inv', 'hard', 3, 'рахунок за запчастини й роботи виставляється в налаштованих журналах')
dep_add('acc', 'inv', 'hard', 1, 'управлінський облік будується на журналах і планові рахунків: спершу «Рахунки та податки», далі кешфлоу й P&L')
dep_add('stk', 'inv', 'soft', 3, 'грошові відхилення інвентаризації проводяться в журнал — потрібні налаштовані рахунки')
dep_add('mrp', 'inv', 'soft', 1, 'собівартість випуску проводиться в журнал запасів')
dep_del('mig', 'acc', 3)
dep_add('mig', 'inv', 'soft', 3, 'початкові сальдо контрагентів заносяться в журнали обліку')

# ---------- 2. База р.1: український фундамент і оглядова сесія ----------
base_inc = items['base']['inc']
base_inc.insert(1, 'українська мова інтерфейсу, часовий пояс і валюта UAH')
base_inc.append('нумерація документів: префікс, рік, лічильник')
base_inc.append('двофакторна автентифікація для адміністраторів')
base_inc.append('оглядова сесія 1 година із записом')
items['base']['bounds'].append('навчання за ролями, письмові інструкції й повторні сесії — позиція «Навчання команди»; у Базі лише оглядова сесія')
# нумерація тепер належить Базі — прибираємо дубль із Друкованих форм
drop('prt', 'inc', 'нумерація штатних документів: префікс, рік, лічильник')
items['prt']['inc'].append('перевірка нумерації у надрукованих документах')

# ---------- 3. Перенесення пунктів ----------
# набори (kit) — зі Складу р.2 у Виробництво р.1
drop('stk', 1, 'комплектація наборів — потребує застосунку «Виробництво»')
items['mrp']['inc'].insert(1, 'набори (kit): специфікація типу «набір», списання складових без виробничого замовлення')
rep('mrp', 'inc', 'специфікація виробу', 'специфікація виробу (BoM)')
items['mrp']['lv'][0][3] = 'збірка на замовлення, набори з готових компонентів або одна специфікація'
dep_del('stk', 'mrp', 2)
items['stk']['apps']['2'] = [m for m in items['stk']['apps']['2'] if m != 'mrp']  # набори переїхали — Склад більше не ставить mrp
items['stk']['bounds'].append('комплектація наборів (kit) — у позиції «Виробництво»: у Складі механізму немає')
# партії й серійні номери — зі Складу р.3 у р.2
moved = drop('stk', 2, 'облік партій або серійних номерів')
items['stk']['lv'][1][4].insert(1, moved)
items['stk']['lv'][1][3] = 'кілька місць зберігання, резервування під замовлення або облік партій і серійних номерів'
items['stk']['lv'][2][3] = 'складів більше одного або інвентаризації з грошовими відхиленнями'
items['stk']['q'] = 'Скільки місць зберігання, чи резервуєте товар і чи обліковуєте партії?'
# Оренді тепер достатньо Складу р.2
for d in items['rnt']['dep']:
    if d['on'] == 'stk':
        d['min_lv'] = 2
        d['why'] = 'графік оренд по серійниках вимагає Складу з увімкненими партіями й серійними номерами (перевірено на стенді)'

# ---------- 4. Картки виконавців у базові пункти ----------
CARD = 'картки виконавців-співробітників (без кадрового обліку)'
for iid in ('prj', 'exp', 'pln', 'fsm'):
    items[iid]['inc'].append(CARD)

io.open(PRICE, 'w', encoding='utf-8').write(json.dumps(p, ensure_ascii=False, indent=2) + '\n')
pos = sum(len(g['items']) for g in groups)
pts = sum(len(it['inc']) + sum(len(it['lv'][k][4]) for k in (1, 2)) for g in groups for it in g['items'])
deps = sum(len(it.get('dep', [])) for g in groups for it in g['items'])
print('OK: %d груп, %d позицій, %d пунктів складу, %d залежностей' % (len(groups), pos, pts, deps))
