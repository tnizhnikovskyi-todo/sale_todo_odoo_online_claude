#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Рішення власника 05.09.2026: регламентний облік іде з контуру повністю.

Ми не налаштовуємо в базі клієнта бухгалтерський, податковий і кадровий облік,
не обіцяємо його і не обговорюємо. Наслідки для прайсу:

    • позиція inv «Рахунки та податки» → «Рахунки та оплати»: журнали, умови
      оплати, банк і каса. План рахунків ПСБО, ставки ПДВ, статус платника
      й фіскальні позиції зі складу робіт зникають, l10n_ua — з apps/home
    • з ознак рівнів, складу робіт і пояснень залежностей іде мова про ПДВ,
      план рахунків і «Бухгалтерію» — замість неї назви позицій прайсу
    • з «не входить» ідуть рядки, що перелічують регламентні документи й
      згадують BAS: межа лишається одна, у тексті КП
    • ПРРО й фіскальний чек лишаються: це не облік у базі, а межа платформи,
      за якою вирішується, чи продаємо Точку продажу взагалі

Години не змінюються: вони гіпотези до замірів фази 0.
Запуск: python3 docs/аналіз-прайсу/скрипти/apply_decisions_2026-09-05.py
"""
import io, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
DATA = os.path.join(ROOT, 'data', 'price.json')

payload = json.load(io.open(DATA, encoding='utf-8'))
BY = {it['id']: it for g in payload['групи'] for it in g['items']}

def drop(lst, text):
    assert text in lst, 'не знайдено для видалення: %s' % text
    lst.remove(text)

def swap(lst, old, new):
    assert old in lst, 'не знайдено для заміни: %s' % old
    lst[lst.index(old)] = new

# ---------- inv: «Рахунки та податки» → «Рахунки та оплати» ----------
inv = BY['inv']
assert inv['n'] == 'Рахунки та податки'
inv['n'] = 'Рахунки та оплати'
inv['d'] = 'журнали, умови оплати, банк, каса'
drop(inv['inc'], 'план рахунків ПСБО і ставки ПДВ 20/14/7/0 (штатний l10n_ua)')
drop(inv['inc'], 'статус платника ПДВ і податки в товарах і контрагентах')
inv['inc'] += ['нумерація рахунків і платежів',
               'реєстрація оплат і зіставлення з рахунками']
inv['lv'][0][3] = 'один банк, одна каса, рахунки виписує одна людина'
inv['lv'][1][3] = 'кілька банків чи кас або потрібен імпорт банківської виписки'
drop(inv['lv'][1][4], 'фіскальні позиції для неплатника ПДВ і експорту (у l10n_ua їх немає — налаштовуються під клієнта)')
inv['lv'][2][3] = 'кілька юросіб або розрахунки у валюті'
swap(inv['lv'][2][4], 'журнали, податки й нумерація для кожної юрособи',
                      'журнали, нумерація й реквізити для кожної юрособи')
swap(inv['lv'][2][4], 'валютні рахунки; курси НБУ — вручну або імпортом',
                      'валютні рахунки; курс вводиться вручну або імпортом')
inv['q'] = 'Хто виписує рахунки клієнтам і скільки банків та кас у роботі?'
drop(inv['bounds'], 'податкові накладні, РК, ЄРПН і ПДВ-звітність — у BAS у вашого бухгалтера')
drop(inv['bounds'], 'каса Odoo — управлінський журнал, не касова книга')
swap(inv['bounds'], 'курси НБУ автоматично не завантажуються',
                    'курс валюти автоматично не завантажується')
swap(inv['bounds'], 'первинні документи українського зразка (рахунок, видаткова, акт) — позиція «Друковані форми»',
                    'бланки рахунка, видаткової чи акта вашого зразка — позиція «Друковані форми»')
inv['apps']['1'].remove('l10n_ua')
inv['home'].remove('l10n_ua')

# ---------- acc: управлінський облік будується на документах самої Odoo ----------
acc = BY['acc']
acc['apps']['1'].remove('l10n_ua')
drop(acc['bounds'], 'регламентний облік, ПДВ-звітність, ПН — у BAS')
drop(acc['bounds'], 'Фіскальних позицій у l10n_ua немає — правила для неплатника ПДВ чи експорту налаштовуються під клієнта')
drop(acc['bounds'], 'каса Odoo — управлінський журнал, не касова книга')
swap(acc['bounds'], 'регулярне завантаження даних з BAS — регламент і відповідальна особа клієнта, умова старту',
                    'звіти читаються з документів, створених у самій Odoo; завантаження даних із зовнішніх систем не входить')
swap(acc['bounds'], 'курси НБУ — вручну або імпортом', 'курс валюти — вручну або імпортом')
swap(acc['lv'][2][4], 'кілька валют у документах і звітах; курси НБУ — імпортом, автозавантаження немає',
                      'кілька валют у документах і звітах; курс — імпортом, автозавантаження немає')

# ---------- пояснення залежностей ----------
DEP_WHY = {
  'рахунок клієнту чи постачальнику виписується в налаштованих журналах із правильною ставкою ПДВ — це позиція «Рахунки та податки»':
    'рахунок клієнту чи постачальнику виписується в налаштованому журналі з нумерацією й умовами оплати — це позиція «Рахунки та оплати»',
  'рахунок за витраченим часом виставляється в журналі продажів із ставкою ПДВ':
    'рахунок за витраченим часом виставляється в налаштованому журналі продажів',
  'замовлення магазину — це замовлення Продажів: прайс, податки, політика рахунків, підтвердження':
    'замовлення магазину — це замовлення Продажів: прайс, політика рахунків, підтвердження',
  'зведений Баланс і P&L, Multi-Ledger і мапінг рахунків живуть у Бухгалтерії; рівень «лише рух коштів» для цього замалий':
    'зведений P&L по групі й мапінг рахунків — рівень 2+ позиції «Управлінський облік»; «лише рух коштів» для цього замалий',
  'інвентаризація з відхиленнями в грошах і рахунок втрат — оцінка запасів у Бухгалтерії':
    'інвентаризація з відхиленнями в грошах — оцінка запасів у позиції «Управлінський облік»',
  '«бюджети й контроль перевищень» — бюджети аналітики, модуль Budget Management у Бухгалтерії':
    '«бюджети й контроль перевищень» — бюджети аналітики, рівень 3 позиції «Управлінський облік»',
  '«звірка з корпоративними картками» — банківська виписка й звірка в Бухгалтерії':
    '«звірка з корпоративними картками» — банківська виписка й звірка в позиції «Управлінський облік»',
  '«порівняння періодів у фінансових звітах» — звіти Бухгалтерії':
    '«порівняння періодів у фінансових звітах» — звіти позиції «Управлінський облік»',
  'управлінський облік будується на журналах і планові рахунків: спершу «Рахунки та податки», далі кешфлоу й P&L':
    'кешфлоу й P&L читаються з журналів і документів, які налаштовує позиція «Рахунки та оплати»',
}
seen = set()
for it in BY.values():
    for d in it.get('dep', []) or []:
        if d.get('why') in DEP_WHY:
            seen.add(d['why']); d['why'] = DEP_WHY[d['why']]
assert seen == set(DEP_WHY), 'не знайдені пояснення: %s' % (set(DEP_WHY) - seen)

# ---------- «не входить»: прибираємо перелік регламентних документів і згадки BAS ----------
DROP = {
  'base': ['регламентний облік і звітність — у BAS'],
  'mco':  ['регламентний облік кожної юрособи — у її BAS'],
  'sal':  ['податкові накладні й первинка за формою України — у BAS'],
  'pur':  ['оплати постачальникам і борг — регламентний облік у BAS'],
  'sub':  ['рахунок з Odoo — управлінський; акти й ПН — у BAS'],
  'exp':  ['авансовий звіт за формою та ПДФО — у BAS'],
  'hr':   ['зарплата, накази, табель, особові картки П-2, військовий облік — у BAS або кадровій системі',
           'розрахунок відпускних — у BAS',
           'Розрахунку зарплати для України немає — модуля l10n_ua_hr_payroll не існує'],
  'dsh':  ['даних з BAS (податки, зарплата) у дашбордах немає',
           'звіти за формами регламентної звітності — немає'],
  'prt':  ['ТТН, податкова накладна, регламентовані форми — у BAS'],
}
for iid, lines in DROP.items():
    for t in lines: drop(BY[iid]['bounds'], t)

SWAP = {
  'pur': [('імпорт: ВМД — у BAS, курси валют — вручну', 'курс валюти вводиться вручну')],
  'stk': [('складські документи українського зразка, ТТН, оцінка запасів для звітності — у BAS',
           'складські документи вашого зразка — позиція «Друковані форми»')],
  'mrp': [('бухгалтерська собівартість продукції — у BAS',
           'собівартість — операційна оцінка Odoo за обраним методом')],
  'pln': [('табель і оплата за годинами — у BAS', 'оплата за відпрацьованими годинами не рахується')],
  'fsm': [('підпис на планшеті — не первинний документ для бухгалтерії',
           'підпис на планшеті — підтвердження виконаних робіт, юридичної сили не має')],
  'doc': [('підпис Odoo Sign — простий електронний підпис, не КЕП; первинка з контрагентами й кадрові документи — ЕДО поза Odoo',
           'підпис Odoo Sign — простий електронний підпис, не КЕП: юридично значущі документи з контрагентами так не підписуються'),
          ('інтеграції з «Вчасно», M.E.Doc, Paperless — немає',
           'інтеграцій із зовнішніми системами документообігу немає')],
  'prt': [('бланк друкується з даних, які є в Odoo', 'бланк друкується з даних, які є в Odoo')],
}
for iid, pairs in SWAP.items():
    for old, new in pairs:
        if old == new:
            if new not in BY[iid]['bounds']: BY[iid]['bounds'].append(new)
        else:
            swap(BY[iid]['bounds'], old, new)

# hr: рівень 2 — прибираємо перелік кадрових форм
swap(BY['hr']['lv'][2][4],
     'файли співробітника в Документах, версії умов найму; кадрові накази, табель і форми Держстату — поза периметром (BAS)',
     'файли співробітника в Документах, версії умов найму')
BY['hr']['bounds'].append('позиція веде облік відсутностей і картки співробітників; розрахунок виплат не входить')
# exp: рівень 3 — аванс без «Бухгалтерії»
swap(BY['exp']['lv'][2][4],
     'аванс співробітнику — платежем контрагенту із зіставленням у Бухгалтерії; авансовий звіт за формою — у BAS',
     'аванс співробітнику — платежем із зіставленням у позиції «Рахунки та оплати»')

io.open(DATA, 'w', encoding='utf-8').write(
    json.dumps(payload, ensure_ascii=False, indent=2) + '\n')
print('price.json: регламентний облік прибрано з прайсу')
