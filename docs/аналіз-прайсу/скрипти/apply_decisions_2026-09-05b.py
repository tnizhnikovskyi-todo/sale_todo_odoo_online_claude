#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Рішення власника 05.09.2026, продовження: ПРРО і КЕП теж ідуть із матеріалів.

Фіскалізація каси й способи підписання документів — теми того самого ряду, що й
регламентний облік: вони не наша робота, і в прайсі, чек-листі й КП їх немає.
Замість них — операційні формулювання того, що позиція справді робить:

    • Точка продажу: «чек продажу й повернення», питання про кількість кас;
      меж про ПРРО, фіскальний реєстратор і нефіскальний чек більше немає
    • Документи й підписи, Продажі: Odoo Sign описується як підписання
      у браузері за посиланням, без порівняння з КЕП
    • Проєкти, Підписки, Оренда, Інтернет-магазин: рядки «не входить» про ПРРО
      й акти з КЕП прибрані або переписані на бланки «Друкованих форм»

Гейти кваліфікації лишаються, але питають про обсяг і спосіб роботи, а не про
фіскалізацію: роздріб на десятки чеків щодня — не наш контур; підписання, яке
має замінити офіційний обмін документами, — теж.

Запуск: python3 docs/аналіз-прайсу/скрипти/apply_decisions_2026-09-05b.py
"""
import io, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
PRICE = os.path.join(ROOT, 'data', 'price.json')
QUAL = os.path.join(ROOT, 'data', 'qualification.json')

payload = json.load(io.open(PRICE, encoding='utf-8'))
BY = {it['id']: it for g in payload['групи'] for it in g['items']}

def drop(lst, text):
    assert text in lst, 'не знайдено для видалення: %s' % text
    lst.remove(text)

def swap(lst, old, new):
    assert old in lst, 'не знайдено для заміни: %s' % old
    lst[lst.index(old)] = new

# ---------- Точка продажу: операційна каса, без фіскальної теми ----------
pos = BY['pos']
swap(pos['inc'], 'чек Odoo (нефіскальний) і повернення; фіскалізація через ПРРО — поза периметром, клієнт веде окремо',
                 'чек продажу й повернення')
pos['lv'][0][3] = 'одна каса, готівка й картка'
pos['q'] = 'Скільки кас і точок продажу?'
drop(pos['bounds'], 'чек Odoo — нефіскальний; ПРРО, фіскальний реєстратор і банківський термінал клієнт веде окремо')
drop(pos['bounds'], 'Фіскалізації (ПРРО) в Odoo Online немає — фіскальний чек формується поза Odoo; POS працює як касовий облік')
swap(pos['bounds'], 'підакцизні й ліцензовані товари — позиція не продається',
                    'ліцензовані товари й товари з обов’язковим маркуванням — позиція не продається')
pos['bounds'].append('каса в Odoo — операційний облік продажів і залишків; усе, що потрібно касі поза цим, клієнт забезпечує сам')

# ---------- Продажі: Odoo Sign без порівняння з КЕП ----------
sal = BY['sal']
swap(sal['lv'][1][4], 'електронний підпис Odoo Sign — простий електронний підпис, не КЕП',
                      'електронний підпис Odoo Sign — погодження КП у браузері за посиланням')
swap(sal['bounds'], 'підпис Odoo Sign — простий електронний підпис, не КЕП',
                    'підпис Odoo Sign — погодження в браузері за посиланням; інших способів підписання позиція не закриває')

# ---------- Документи й підписи ----------
doc = BY['doc']
doc['lv'][1][3] = 'узгодження документів і підписання у браузері за посиланням'
swap(doc['lv'][1][4], 'електронний підпис Odoo Sign — простий електронний підпис, не КЕП',
                      'електронний підпис Odoo Sign — підписання у браузері за посиланням')
swap(doc['bounds'], 'підпис Odoo Sign — простий електронний підпис, не КЕП: юридично значущі документи з контрагентами так не підписуються',
                    'підпис Odoo Sign — підписання у браузері за посиланням; замінити ним офіційний обмін документами з контрагентами не можна')

# ---------- решта рядків «не входить» ----------
drop(BY['shop']['bounds'], 'фіскальні чеки за онлайн-оплату й післяплату — ПРРО клієнта поза Odoo')
drop(BY['sub']['bounds'], 'оплати B2C карткою — ПРРО клієнта')
swap(BY['rnt']['bounds'], 'готівка й картка від фізосіб — ПРРО клієнта; договір оренди бланком — позиція «Друковані форми»',
                          'договір оренди бланком — позиція «Друковані форми»')
swap(BY['prj']['bounds'], 'рахунки за часом — управлінські; акти з КЕП — поза Odoo',
                          'акт за виконаними годинами вашого зразка — позиція «Друковані форми»')

io.open(PRICE, 'w', encoding='utf-8').write(json.dumps(payload, ensure_ascii=False, indent=2) + '\n')
print('price.json: ПРРО і КЕП прибрані')

# ---------- чек-лист: гейти про обсяг і спосіб роботи ----------
import collections
qual = json.loads(io.open(QUAL, encoding='utf-8').read(), object_pairs_hook=collections.OrderedDict)
scr = [b for b in qual['блоки'] if b['id'] == 'scr'][0]
byid = {q['id']: q for q in scr['питання']}

cash = byid['cash']
cash['q'] = 'Чи продають фізособам за готівку або картку і скільки чеків на день?'
cash['a'] = [
    collections.OrderedDict([('t', 'Ні, платять тільки юрособи на рахунок'), ('r', 'ok')]),
    collections.OrderedDict([('t', 'Так, кілька чеків на день'), ('r', 'warn'),
        ('note', 'Каса в Odoo — операційний облік продажів і залишків: чеки, зміни, звіт за зміну. Усе, що потрібно касі поза цим, клієнт забезпечує сам — сказати вголос до КП.'),
        ('need', ['pos'])]),
    collections.OrderedDict([('t', 'Так, десятки чеків щодня'), ('r', 'stop'),
        ('note', 'Роздріб такого обсягу вимагає окремого касового контуру, якого ми не налаштовуємо. Лід передати в основну команду.')]),
]

sign = byid['sign']
sign['q'] = 'Чи є документи, які клієнт хоче підписувати «в системі», і з ким саме?'
sign['a'] = [
    collections.OrderedDict([('t', 'Не потрібно'), ('r', 'ok')]),
    collections.OrderedDict([('t', 'Усередині компанії й комерційні погодження'), ('r', 'warn'),
        ('note', 'Odoo Sign годиться: підписання у браузері за посиланням — погодження, комерційні пропозиції, внутрішні документи.'),
        ('need', ['doc'])]),
    collections.OrderedDict([('t', 'Підпис має замінити офіційний обмін документами з контрагентами'), ('r', 'stop'),
        ('note', 'Odoo Sign так не працює: це підписання у браузері за посиланням. Замінити ним офіційний обмін документами не можна — це не наш контур.')]),
]

io.open(QUAL, 'w', encoding='utf-8').write(json.dumps(qual, ensure_ascii=False, indent=2) + '\n')
print('qualification.json: гейти переписані на обсяг і спосіб роботи')
