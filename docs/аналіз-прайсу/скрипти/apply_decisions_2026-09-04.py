#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Рішення власника від 04.09.2026.

1. Ціна Бази: чотири нові пункти (мова/часовий пояс/валюта, нумерація, 2FA, оглядова сесія)
   входять у базові пункти, отже в усі три рівні → +4 год на кожен рівень: 16/20/28 (€800/1000/1400).
   Це гіпотеза до заміру фази 0, як і решта годин.
2. Прибрано з прайсу все, що не вдалося перевірити на стенді 03.09.2026:
   SMS-код у підписі, переоцінка курсових різниць, конвертація валют у зведеному звіті групи.
   Замість обіцянок — рядки в «не входить» із причиною.
3. Карта налаштування й супровід запуску після передачі — не входять (рішення: прибрати з КП).

Запуск з кореня репозиторію: python3 docs/аналіз-прайсу/скрипти/apply_decisions_2026-09-04.py
"""
import io, json, os

PRICE = os.path.join(os.getcwd(), 'data', 'price.json')
p = json.load(io.open(PRICE, encoding='utf-8'))
items = {it['id']: it for g in p['групи'] for it in g['items']}

def rep(iid, where, old, new):
    l = items[iid]['inc'] if where == 'inc' else items[iid]['lv'][where][4]
    hits = [i for i, s in enumerate(l) if s == old]
    assert len(hits) == 1, 'не знайдено або дубль: %s/%s «%s»' % (iid, where, old)
    l[hits[0]] = new

def drop(iid, where, old):
    l = items[iid]['inc'] if where == 'inc' else items[iid]['lv'][where][4]
    hits = [i for i, s in enumerate(l) if s == old]
    assert len(hits) == 1, 'не знайдено або дубль: %s/%s «%s»' % (iid, where, old)
    l.pop(hits[0])

# ---------- 1. ціна Бази ----------
for i, add in enumerate([4, 4, 4]):
    items['base']['lv'][i][1] += add
assert [l[1] for l in items['base']['lv']] == [16, 20, 28]

# ---------- 2. прибрати неперевірене ----------
# SMS-код: акаунта sms на стенді немає, кредитів 0 — доставка на +380 не перевірена
rep('sal', 1, 'електронний підпис Odoo Sign — простий підпис із SMS-кодом, не КЕП',
    'електронний підпис Odoo Sign — простий електронний підпис, не КЕП')
rep('doc', 1, 'електронний підпис Odoo Sign — простий підпис із SMS-кодом, не КЕП',
    'електронний підпис Odoo Sign — простий електронний підпис, не КЕП')
SMS = 'підтвердження підписанта SMS-кодом вимагає платних кредитів IAP клієнта; доставку на українські номери не перевіряли'
items['sal']['bounds'].append(SMS)
items['doc']['bounds'].append(SMS)
# переоцінка курсових різниць — на стенді одна компанія й одна валюта
rep('acc', 2, 'кілька валют з переоцінкою; курси НБУ — імпортом, автозавантаження немає',
    'кілька валют у документах і звітах; курси НБУ — імпортом, автозавантаження немає')
items['acc']['bounds'].append('переоцінку курсових різниць на стенді не перевіряли (пробна база — одна компанія, одна валюта): перевіряється до обіцянки клієнту')
items['acc']['bounds'].append('перелік банків для синхронізації видно лише в майстрі інтерфейсу — до продажу перевіряємо разом із клієнтом')
# конвертація валют у зведеному звіті групи — не перевірена
drop('mco', 2, 'кілька валют у структурі')
items['mco']['bounds'].append('конвертацію валют у зведеному звіті по групі на стенді не перевіряли (одна компанія): перевіряється до продажу')

# ---------- 3. карта налаштування й супровід — не входять ----------
items['base']['bounds'].append('карта налаштування бази і супровід після передачі — не входять; гарантія на дефекти конфігурації діє 10 робочих днів після приймання позиції')

io.open(PRICE, 'w', encoding='utf-8').write(json.dumps(p, ensure_ascii=False, indent=2) + '\n')
print('База: %s год → €%s | прибрано неперевірених обіцянок: 3' % ([l[1] for l in items['base']['lv']], [l[1]*50 for l in items['base']['lv']]))
